function relativeLuminance(hex: string): number {
    const channels = [1, 3, 5].map(index => Number.parseInt(hex.slice(index, index + 2), 16) / 255);
    const [red, green, blue] = channels.map(channel => (
        channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4
    ));
    return 0.2126 * red + 0.7152 * green + 0.0722 * blue;
}

function contrastRatio(foreground: string, background: string): number {
    const values = [relativeLuminance(foreground), relativeLuminance(background)].sort((a, b) => b - a);
    return (values[0] + 0.05) / (values[1] + 0.05);
}

function themeHex(name: string): string {
    const match = globals.match(new RegExp(`--color-${name}:\\s*(#[0-9a-f]{6})`, 'i'));
    if (!match) throw new Error(`Missing theme color: ${name}`);
    return match[1];
}

const compactSummary = resultPage.slice(
    resultPage.indexOf('{summary.v2 && counts ? ('),
    resultPage.indexOf(') : gr ? ('),
);
const legacySummary = resultPage.slice(
    resultPage.indexOf(') : gr ? ('),
    resultPage.indexOf('{/* public / private tabs */}'),
);
const verdictPresentation = `${compactSummary}\n${highRiskSummary}`;

const reportHeader = resultPage.slice(
    resultPage.indexOf('<Eyebrow className="shrink-0">판독 리포트</Eyebrow>'),
    resultPage.indexOf('{/* pipeline-specific summary */}'),
);
const v2Hero = resultPage.slice(
    resultPage.indexOf('{summary.v2 && counts ? ('),
    resultPage.indexOf('<HighRiskSummary'),
);

describe('result page pagination copy contract', () => {
    it('drops the range/plus counters and the old load-more buttons', () => {
        for (const forbidden of [
            'paginatedRangeLabel',
            'paginatedCountLabel',
            '더 보기',
            '이전 목록',
            'ResultPaginationControls',
        ]) {
            expect(resultPage).not.toContain(forbidden);
        }
        // A "1-50+" style range is generated by combining a hyphen range with a
        // trailing "+"; neither the helpers nor that shape should survive.
        expect(resultPage).not.toMatch(/\d+-\d+\+/);
    });

    it('removes the range/count label helpers from the presentation module', () => {
        expect(presentation).not.toContain('paginatedRangeLabel');
        expect(presentation).not.toContain('paginatedCountLabel');
    });

    it('marks the active page with aria-current in the numbered pager', () => {
        expect(pagination).toContain("aria-current={item.current ? 'page' : undefined}");
    });

    it('keeps accessible gender text labels while icons are decorative', () => {
        expect(resultPage).toContain("from 'lucide-react'");
        expect(resultPage).toContain('OWNER_GENDER_LABELS.male');
        expect(resultPage).toContain('OWNER_GENDER_LABELS.female');
        expect(resultPage).toContain('OWNER_GENDER_LABELS.unknown');
        // The gender icons must be aria-hidden so the retained text carries meaning.
        expect(resultPage).toContain('<row.Icon aria-hidden="true"');
    });

    it('omits the screened-count header while retaining the gender breakdown and account tabs', () => {
        expect(resultPage).not.toContain('판독 {counts.screened.toLocaleString()}명');
        expect(resultPage).toContain('<GenderRatioBreakdown gr={gr} />');
        expect(resultPage).toContain("label: '공개 계정(여성)'");
        expect(resultPage).toContain("label: '비공개 계정'");
        expect(resultPage).toContain('summary.v2.privateMutuals.toLocaleString()');
    });

    it('counts the public tab by the rows it actually lists', () => {
        // The public tab lists female-classified accounts only. Counting every
        // public mutual overstated it roughly threefold, so the number has to
        // come from the same female slice the distribution bar shows.
        expect(resultPage).toContain('gr ? gr.female.count : femaleAccounts.length');
        expect(resultPage).not.toContain('summary.v2.publicMutuals.toLocaleString()');
    });

    it('keeps profile images behind the exact local/proxy boundary', () => {
        expect(resultPage).toContain("import { safeResultImageUrl } from '@/lib/services/result-local-image'");
        expect(resultPage).toContain('const proxiedSrc = safeResultImageUrl(src)');
        expect(resultImageBoundary).toContain("url.startsWith('/api/image-proxy?')");
        expect(resultImageBoundary).toContain('demo-v3-(?:target|female|private)');
        expect(resultImageBoundary).toContain("? url\n        : undefined");
    });

    it('keeps V2 owner results out of the legacy share action', () => {
        expect(resultPage).toContain("data.pipelineVersion === 'v1'");
        expect(resultPage).not.toContain("data.pipelineVersion === 'v2' && <div className=\"mt-9\">");
    });

    it('states the analysis scope once and drops profile vanity metrics', () => {
        // Mutual count describes what was analysed, so it rides the verdict line.
        expect(compactSummary).toContain('counts.mutual.toLocaleString()');
        // Follower/following describe the account, not the result, and preflight
        // already showed them; repeating them here only thickened the header.
        expect(resultPage).not.toContain('summary.v2.followers.declared.toLocaleString()');
        expect(resultPage).not.toContain('summary.v2.following.declared.toLocaleString()');
        // Internal screening scope is never surfaced to the owner.
        expect(resultPage).not.toContain('summary.v2.screenedMutuals.toLocaleString()');
    });

    it('keeps the share control inside the report, not in the app chrome', () => {
        // In the TopBar it read as a site-level menu item rather than an action
        // on this result.
        expect(reportHeader).toContain('handleKakaoShare');
        const topBar = resultPage.slice(resultPage.indexOf('<TopBar'), resultPage.indexOf('</TopBar>') + 1);
        expect(topBar).not.toContain('handleKakaoShare');
    });

    it('states the account split once, on the tabs', () => {
        // The counts already label the tabs below the summary, so a separate
        // metric strip repeating them would be dead weight.
        expect(resultPage).not.toContain('MetricStrip');
        expect(resultPage).toContain('summary.v2.privateMutuals.toLocaleString()');
    });

    it('keeps every gender label inside the bar it belongs to', () => {
        /* Position used to carry the proportion, with each label centred under
           its own slice. That only holds while every slice can hold a label: at
           6% 미상 the label ran well past its segment and sat over 여자, so
           position was contradicting the bar instead of restating it. The three
           labels are now pinned to the bar's own edges. */
        expect(resultPage).not.toContain('style={{ width: `${row.c.percentage}%` }}');
        expect(resultPage).toContain("align: 'justify-start'");
        expect(resultPage).toContain("align: 'justify-center'");
        expect(resultPage).toContain("align: 'justify-end'");
        // The bar still carries the proportion, so no printed percentages.
        expect(resultPage).not.toContain('{row.c.percentage}%</span>');
    });

    it('gives the report a headline naming the analysed account', () => {
        expect(compactSummary).toContain('님의 위장 여사친');
        // Instagram display names are optional, so the handle backs the headline
        // until (and when) targetFullName is absent.
        expect(compactSummary).toContain('targetHeader.displayName');
        expect(resultPage).toContain('targetFullName?: string | null');
    });

    it('binds the hero identity and Instagram link to the canonical target summary', () => {
        // The header must project only the stored target identity. Keeping that
        // projection in one helper prevents future result-row work from making a
        // candidate name or handle leak into the hero.
        expect(resultPage).toContain("import { resultPageHeader } from '@/lib/services/analysis/result-page-header'");
        expect(resultPage).toContain('const targetHeader = resultPageHeader(summary);');
        expect(v2Hero).toContain('{targetHeader.displayName}');
        expect(v2Hero).toContain('님의 위장 여사친');
        expect(v2Hero).toContain('href={targetHeader.instagramUrl}');
        expect(v2Hero).toContain('@{targetHeader.username}');
        expect(v2Hero).toContain('target="_blank"');
        expect(v2Hero).toContain('rel="noopener noreferrer"');
    });

    it('never rebuilds the summary as a grid of bordered cells', () => {
        expect(compactSummary).not.toContain('mt-2 grid grid-cols-3');
        expect(compactSummary).not.toContain('grid-cols-2 gap-px bg-line');
        expect(compactSummary).not.toContain('block text-[10px]');
    });

    it('leads the summary with the high-risk verdict rather than raw counts', () => {
        // The verdict used to sit outside the summary container in 13px grey
        // while secondary counts held the frame; it now opens the page.
        expect(verdictPresentation).toContain('count={highCount}');
        expect(verdictPresentation).toContain('고위험 계정');
        expect(compactSummary).not.toContain('INSTAGRAM 원지표');
    });

    it('keeps the V1 verdict scoped to the authoritative mutual count', () => {
        expect(legacySummary).toMatch(
            /<HighRiskSummary[\s\S]*?count=\{highCount\}[\s\S]*?context=\{<>\s*맞팔[\s\S]*?summary\.analyzedMutuals\.toLocaleString\(\)[\s\S]*?모든 공개 계정들을 판독했습니다\.\s*<\/>\}\s*\/>/,
        );
    });

    it('does not paint a clean verdict in the danger accent', () => {
        // Zero high-risk accounts is the best outcome; rendering it in crimson
        // would make the safest result read as the most alarming one.
        expect(verdictPresentation).toContain("safeCount > 0 ? 'text-blood-2' : 'text-jade'");
        // The rail is an absolutely-positioned span so it can draw downward.
        expect(verdictPresentation).toContain("safeCount > 0 ? 'bg-blood' : 'bg-jade'");
    });

    it('reveals the header in hierarchy order and survives reduced motion', () => {
        // Motion should teach the reading order — subject, verdict, context,
        // distribution — rather than fade everything in at once.
        // Anchored on class names: in JSX the style attribute follows className,
        // so the nearest delay after the anchor belongs to that element.
        const delayOf = (className: string) => {
            const at = verdictPresentation.indexOf(className);
            expect(at, `missing anchor: ${className}`).toBeGreaterThan(-1);
            const found = /animationDelay: '(\d+)ms'/.exec(verdictPresentation.slice(at, at + 400));
            return Number(found?.[1] ?? NaN);
        };
        const lockup = delayOf('reveal mt-5 flex items-start');
        const rail = delayOf('reveal-rail absolute');
        const label = delayOf('reveal mt-3 text-[17px]');
        const context = delayOf('reveal mt-1 text-[12.5px]');
        expect(lockup).toBeLessThan(rail);
        expect(rail).toBeLessThan(label);
        expect(label).toBeLessThan(context);
        // The count-up is JS-driven, so the CSS reduced-motion block cannot cover
        // it; the hook has to opt out on its own.
        expect(highRiskSummary).toContain('useCountUp');
        expect(globals).toContain('prefers-reduced-motion');
    });

    it('drops the bordered container and corner brackets from the summary', () => {
        // Corner brackets are reserved for the screen's verdict (high-risk rows,
        // errors); a summary wrapped in them makes the device meaningless.
        expect(compactSummary).not.toContain('<CaseCard');
    });

    it('uses WCAG-AA text colors for every essential summary metric', () => {
        // fg-mute clears neither ground at AA, so it must never carry a metric
        // label or value at any size — demotion is size and weight, not contrast.
        expect(compactSummary).not.toContain('text-fg-mute');
        expect(reportHeader).not.toContain('text-fg-mute');
        expect(resultPage).toContain("txt: 'text-blood-2'");
        for (const foreground of ['fg', 'fg-dim', 'blood-2']) {
            expect(contrastRatio(themeHex(foreground), themeHex('ink-2'))).toBeGreaterThanOrEqual(4.5);
            expect(contrastRatio(themeHex(foreground), themeHex('panel'))).toBeGreaterThanOrEqual(4.5);
        }
        expect(contrastRatio(themeHex('fg-mute'), themeHex('ink'))).toBeLessThan(4.5);
    });
});
