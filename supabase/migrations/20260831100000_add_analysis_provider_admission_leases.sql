CREATE OR REPLACE FUNCTION public.analysis_provider_admission_json(
    p_lease public.analysis_provider_admission_leases,
    p_outcome TEXT,
    p_active_count INTEGER,
    p_max_active INTEGER,
    p_job_claim_token UUID,
    p_provider_claim_token UUID
)
RETURNS JSONB
LANGUAGE SQL
STABLE
SET search_path = ''
AS $$
    SELECT pg_catalog.jsonb_build_object(
        'outcome', p_outcome,
        'admissionId', p_lease.admission_id,
        'workloadRole', p_lease.workload_role,
        'logicalProvider', p_lease.logical_provider,
        'credentialSlot', p_lease.credential_slot,
        'budgetKey', p_lease.budget_key,
        'operationKey', p_lease.operation_key,
        'requestId', pg_catalog.lower(p_lease.request_id::TEXT),
        'jobKey', p_lease.job_key,
        -- The lease secret is returned only to the exact current durable claim.
        -- This is a defense-in-depth check in addition to the claim validation in
        -- acquire; a stale/mis-bound replay must never receive a live secret.
        'leaseToken', CASE WHEN p_lease.state = 'leased'
                                AND p_lease.job_claim_token IS NOT DISTINCT FROM p_job_claim_token
                                AND p_lease.claim_token IS NOT DISTINCT FROM p_provider_claim_token
                           THEN p_lease.lease_token ELSE NULL END,
        'fence', CASE WHEN p_lease.state = 'leased'
                           AND p_lease.job_claim_token IS NOT DISTINCT FROM p_job_claim_token
                           AND p_lease.claim_token IS NOT DISTINCT FROM p_provider_claim_token
                      THEN p_lease.fence ELSE NULL END,
        'expiresAt', CASE WHEN p_lease.state = 'leased'
                               AND p_lease.job_claim_token IS NOT DISTINCT FROM p_job_claim_token
                               AND p_lease.claim_token IS NOT DISTINCT FROM p_provider_claim_token
                          THEN p_lease.expires_at ELSE NULL END,
        'activeCount', p_active_count,
        'maxActive', p_max_active
    )
$$;

REVOKE ALL ON FUNCTION public.analysis_provider_admission_json(
    public.analysis_provider_admission_leases, TEXT, INTEGER, INTEGER, UUID, UUID
) FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.assert_analysis_provider_admission_claim(
    p_workload_role TEXT,
    p_logical_provider TEXT,
    p_credential_slot TEXT,
    p_request_id UUID,
    p_job_key TEXT,
    p_operation_key TEXT,
    p_job_claim_token UUID,
    p_provider_claim_token UUID,
    p_provider_fence BIGINT,
    p_now TIMESTAMPTZ
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_preflight public.analysis_preflights%ROWTYPE;
    v_request public.analysis_requests%ROWTYPE;
    v_job public.analysis_pipeline_jobs%ROWTYPE;
    v_request_found BOOLEAN;
    v_job_found BOOLEAN;
    v_preflight_run public.analysis_preflight_provider_runs%ROWTYPE;
    v_v2_run public.analysis_v2_provider_runs%ROWTYPE;
    v_provider_run_found BOOLEAN;
    v_preflight_found BOOLEAN;
    v_policy public.analysis_v2_provider_execution_policies%ROWTYPE;
    v_operation_family TEXT;
    v_policy_slot TEXT;
    v_preflight_order_slot TEXT;
    v_beta_allocation_state TEXT;
    v_beta_reservation_slot TEXT;
    v_beta_reservation_state TEXT;
    v_gemini_lease public.analysis_v2_gemini_leases%ROWTYPE;
    v_gemini_attempt INTEGER;
BEGIN
    -- Initial profile work belongs to the preflight claim. Fresh paid profile
    -- admission uses the paid worker route but still claims the durable
    -- preflight admission row before it may start the provider.
    IF p_workload_role = 'preflight' THEN
        IF p_logical_provider <> 'apify' OR p_job_key <> 'preflight:provider'
           OR p_operation_key <> 'target-profile-fallback' THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CLAIM_CONFLICT', ERRCODE = 'P0001';
        END IF;
        SELECT preflight.* INTO v_preflight
        FROM public.analysis_preflights AS preflight
        WHERE preflight.id = p_request_id
        FOR SHARE;
        v_preflight_found := FOUND;
        -- A betatest preflight-held target profile is a paid-budget
        -- compatibility path. Never let a caller relabel it as ordinary
        -- preflight work to consume the primary/quinary/senary pool.
        IF v_preflight_found AND (
            v_preflight.analysis_entry_channel = 'betatest'
            OR EXISTS (
                SELECT 1
                FROM public.analysis_beta_pool_allocations AS allocation
                JOIN public.analysis_beta_pool_reservations AS reservation
                  ON reservation.allocation_id = allocation.id
                 AND reservation.operation_family = 'target-profile'
                WHERE allocation.preflight_id = p_request_id
                  AND allocation.lifecycle_state = 'preflight_held'
                  AND reservation.lifecycle_state = 'preflight_held'
            )
        ) THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
        END IF;
        IF NOT v_preflight_found
           OR v_preflight.expires_at <= p_now
           OR v_preflight.status IS DISTINCT FROM 'processing'
           OR v_preflight.lease_token IS DISTINCT FROM p_job_claim_token
           OR p_provider_claim_token IS DISTINCT FROM p_job_claim_token
           OR v_preflight.lease_expires_at IS NULL
           OR v_preflight.lease_expires_at <= p_now THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CLAIM_CONFLICT', ERRCODE = 'P0001';
        END IF;
        SELECT provider_run.* INTO v_preflight_run
        FROM public.analysis_preflight_provider_runs AS provider_run
        WHERE provider_run.preflight_id = p_request_id
          AND provider_run.operation_key = p_operation_key;
        v_provider_run_found := FOUND;
        IF v_provider_run_found
           AND (v_preflight_run.logical_provider IS DISTINCT FROM p_logical_provider
                OR v_preflight_run.credential_slot IS DISTINCT FROM p_credential_slot) THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
        END IF;
        -- Ordinary preflight has no V2 request policy. Its provider-run row
        -- and the preflight claim above are the only durable identity checks.
        -- In particular, do not interpret a policy row keyed by an unrelated
        -- request id as authority for this preflight.
        RETURN;
    END IF;

    -- B-lite is dispatched on the preflight queue, but its Gemini work must
    -- consume the shared paid Gemini budget.  The B-lite cache lease is the
    -- authoritative task claim for this narrow identity; do not substitute a
    -- caller-provided role or request/job tuple.
    IF p_workload_role = 'paid'
       AND p_logical_provider = 'gemini'
       AND p_job_key = 'preflight:blite'
       AND p_operation_key = 'gemini:legacy:unknown:attempt:1' THEN
        IF NOT EXISTS (
            SELECT 1
            FROM public.analysis_preflights AS preflight
            JOIN public.precheckout_blite_cache AS cache
              ON cache.preflight_id = preflight.id
            WHERE preflight.id = p_request_id
              AND preflight.status = 'ready'
              AND preflight.expires_at > p_now
              AND cache.state = 'pending'
              AND cache.lease_token = p_job_claim_token
              AND cache.lease_expires_at IS NOT NULL
              AND cache.lease_expires_at > p_now
        ) THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CLAIM_CONFLICT', ERRCODE = 'P0001';
        END IF;
        -- B-lite uses the precheckout cache lease as its job claim, but the
        -- shared eight-slot Gemini row remains the authoritative provider
        -- fence.  Keep those identities separate and require every durable
        -- slot attribute to match the admission request.
        SELECT gemini_lease.* INTO v_gemini_lease
        FROM public.analysis_v2_gemini_leases AS gemini_lease
        WHERE gemini_lease.state = 'leased'
          AND gemini_lease.request_id = p_request_id
          AND gemini_lease.job_key = 'preflight:blite'
          AND gemini_lease.attempt = 1
          AND gemini_lease.lease_claim_token = p_provider_claim_token
          AND gemini_lease.fence = p_provider_fence
          AND gemini_lease.expires_at > p_now
          AND p_credential_slot = ('gemini-' || gemini_lease.slot::TEXT)
        FOR SHARE;
        IF NOT FOUND THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CLAIM_CONFLICT', ERRCODE = 'P0001';
        END IF;
        RETURN;
    END IF;

    -- A betatest target profile is dispatched on the preflight route for
    -- compatibility, but its service-owned preflight-held credit must consume
    -- the paid Apify global/slot budget.  This narrow branch is intentionally
    -- keyed by the immutable processing claim and held target-profile
    -- reservation; a caller cannot opt into it with a role flag or slot name.
    IF p_workload_role = 'paid'
       AND p_logical_provider = 'apify'
       AND p_job_key = 'preflight:provider'
       AND p_operation_key = 'target-profile-fallback' THEN
        SELECT preflight.* INTO v_preflight
        FROM public.analysis_preflights AS preflight
        WHERE preflight.id = p_request_id
        FOR SHARE;
        IF NOT FOUND
           OR v_preflight.expires_at <= p_now
           OR v_preflight.status IS DISTINCT FROM 'processing'
           OR v_preflight.analysis_entry_channel IS DISTINCT FROM 'betatest'
           OR v_preflight.lease_token IS DISTINCT FROM p_job_claim_token
           OR p_provider_claim_token IS DISTINCT FROM p_job_claim_token
           OR v_preflight.lease_expires_at IS NULL
           OR v_preflight.lease_expires_at <= p_now THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CLAIM_CONFLICT', ERRCODE = 'P0001';
        END IF;
        SELECT allocation.lifecycle_state,
               reservation.credential_slot,
               reservation.lifecycle_state
        INTO v_beta_allocation_state,
             v_beta_reservation_slot,
             v_beta_reservation_state
        FROM public.analysis_beta_pool_allocations AS allocation
        JOIN public.analysis_beta_pool_reservations AS reservation
          ON reservation.allocation_id = allocation.id
         AND reservation.operation_family = 'target-profile'
        WHERE allocation.preflight_id = p_request_id
          AND allocation.lifecycle_state = 'preflight_held'
          AND reservation.lifecycle_state = 'preflight_held'
        FOR SHARE;
        IF NOT FOUND
           OR v_beta_allocation_state IS DISTINCT FROM 'preflight_held'
           OR v_beta_reservation_state IS DISTINCT FROM 'preflight_held'
           OR v_beta_reservation_slot IS DISTINCT FROM p_credential_slot
           OR (v_preflight.order_scoped_apify_credential_slot IS NOT NULL
               AND v_preflight.order_scoped_apify_credential_slot
                    IS DISTINCT FROM p_credential_slot) THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
        END IF;
        SELECT provider_run.* INTO v_preflight_run
        FROM public.analysis_preflight_provider_runs AS provider_run
        WHERE provider_run.preflight_id = p_request_id
          AND provider_run.operation_key = p_operation_key;
        v_provider_run_found := FOUND;
        IF v_provider_run_found
           AND (v_preflight_run.logical_provider IS DISTINCT FROM p_logical_provider
                OR v_preflight_run.credential_slot IS DISTINCT FROM p_credential_slot) THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
        END IF;
        RETURN;
    END IF;

    IF p_workload_role = 'paid'
       AND p_logical_provider = 'apify'
       AND p_job_key = 'paid:target-profile'
       AND p_operation_key ~ '^target-profile-fresh-admission:g([1-9]|[1-9][0-9]|100)$' THEN
        SELECT preflight.* INTO v_preflight
        FROM public.analysis_preflights AS preflight
        WHERE preflight.id = p_request_id
        FOR SHARE;
        IF NOT FOUND
           OR v_preflight.expires_at <= p_now
           OR v_preflight.status IS DISTINCT FROM 'ready'
           OR v_preflight.consumed_request_id IS NOT NULL
           OR v_preflight.admission_status IS DISTINCT FROM 'processing'
           OR v_preflight.admission_claim_token IS DISTINCT FROM p_job_claim_token
           OR p_provider_claim_token IS DISTINCT FROM p_job_claim_token
           OR v_preflight.admission_lease_expires_at IS NULL
           OR v_preflight.admission_lease_expires_at <= p_now THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CLAIM_CONFLICT', ERRCODE = 'P0001';
        END IF;
        SELECT provider_run.* INTO v_preflight_run
        FROM public.analysis_preflight_provider_runs AS provider_run
        WHERE provider_run.preflight_id = p_request_id
          AND provider_run.operation_key = p_operation_key;
        v_provider_run_found := FOUND;
        IF v_provider_run_found
           AND (v_preflight_run.logical_provider IS DISTINCT FROM p_logical_provider
                OR v_preflight_run.credential_slot IS DISTINCT FROM p_credential_slot) THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
        END IF;
        -- Fresh admission is keyed by the preflight id, so an execution
        -- policy (which is created only after request consumption) cannot
        -- authorize this route. Validate the immutable lineage instead:
        -- order-scoped slots and the betatest preflight-held target-profile
        -- reservation are both service-owned facts.
        IF v_preflight.order_scoped_apify_credential_slot IS NOT NULL
           AND v_preflight.order_scoped_apify_credential_slot
                IS DISTINCT FROM p_credential_slot THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
        END IF;
        IF v_preflight.analysis_entry_channel = 'betatest' THEN
            SELECT allocation.lifecycle_state,
                   reservation.credential_slot,
                   reservation.lifecycle_state
            INTO v_beta_allocation_state,
                 v_beta_reservation_slot,
                 v_beta_reservation_state
            FROM public.analysis_beta_pool_allocations AS allocation
            JOIN public.analysis_beta_pool_reservations AS reservation
              ON reservation.allocation_id = allocation.id
             AND reservation.operation_family = 'target-profile'
            WHERE allocation.preflight_id = p_request_id
              AND allocation.lifecycle_state = 'preflight_held'
              AND reservation.lifecycle_state = 'preflight_held'
            FOR SHARE;
            IF NOT FOUND
               OR v_beta_allocation_state IS DISTINCT FROM 'preflight_held'
               OR v_beta_reservation_state IS DISTINCT FROM 'preflight_held'
               OR v_beta_reservation_slot IS DISTINCT FROM p_credential_slot THEN
                RAISE EXCEPTION USING
                    MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
            END IF;
        END IF;
        RETURN;
    END IF;

    IF p_workload_role = 'paid' THEN
        SELECT analysis_request.* INTO v_request
        FROM public.analysis_requests AS analysis_request
        WHERE analysis_request.id = p_request_id
          AND analysis_request.pipeline_version = 'v2'
          AND analysis_request.status IN ('pending', 'processing')
        FOR SHARE;
        v_request_found := FOUND;
        SELECT job.* INTO v_job
        FROM public.analysis_pipeline_jobs AS job
        WHERE job.request_id = p_request_id
          AND job.job_key = p_job_key
          AND job.status = 'processing'
          AND job.lease_token = p_job_claim_token
          AND job.lease_expires_at IS NOT NULL
          AND job.lease_expires_at > p_now
        FOR SHARE;
        v_job_found := FOUND;
        IF NOT v_request_found OR NOT v_job_found THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CLAIM_CONFLICT', ERRCODE = 'P0001';
        END IF;

        IF p_logical_provider = 'gemini' THEN
            IF p_credential_slot !~ '^gemini-[1-8]$'
               OR p_operation_key !~ ':attempt:([1-4])$' THEN
                RAISE EXCEPTION USING
                    MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CLAIM_CONFLICT', ERRCODE = 'P0001';
            END IF;
            v_gemini_attempt := substring(
                p_operation_key FROM ':attempt:([1-4])$'
            )::INTEGER;
            SELECT gemini_lease.* INTO v_gemini_lease
            FROM public.analysis_v2_gemini_leases AS gemini_lease
            WHERE gemini_lease.slot = substring(
                p_credential_slot FROM '^gemini-([1-8])$'
            )::SMALLINT
            FOR SHARE;
            IF NOT FOUND
               OR v_gemini_lease.state <> 'leased'
               OR v_gemini_lease.request_id IS DISTINCT FROM p_request_id
               OR v_gemini_lease.job_key IS DISTINCT FROM p_job_key
               OR v_gemini_lease.attempt IS DISTINCT FROM v_gemini_attempt
               OR v_gemini_lease.lease_claim_token IS DISTINCT FROM p_provider_claim_token
               OR v_gemini_lease.fence IS DISTINCT FROM p_provider_fence
               OR v_gemini_lease.expires_at IS NULL
               OR v_gemini_lease.expires_at <= p_now THEN
                RAISE EXCEPTION USING
                    MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CLAIM_CONFLICT', ERRCODE = 'P0001';
            END IF;
            RETURN;
        END IF;

        v_operation_family := CASE
            WHEN p_operation_key LIKE 'target-profile-fresh-admission:%' THEN 'target-profile'
            ELSE pg_catalog.split_part(p_operation_key, ':', 1)
        END;
        -- A consumed preflight can carry an immutable order-scoped slot. It
        -- takes precedence over the ordinary relationship default; the
        -- request policy, when present, must still agree with it.
        SELECT preflight.order_scoped_apify_credential_slot
        INTO v_preflight_order_slot
        FROM public.analysis_preflights AS preflight
        WHERE preflight.id = v_request.preflight_id;
        IF v_preflight_order_slot IS NOT NULL
           AND v_preflight_order_slot IS DISTINCT FROM p_credential_slot THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
        END IF;
        SELECT policy.* INTO v_policy
        FROM public.analysis_v2_provider_execution_policies AS policy
        WHERE policy.request_id = p_request_id;
        IF FOUND THEN
            v_policy_slot := v_policy.operation_slot_map ->> v_operation_family;
            -- Historical authorized-test policies intentionally contain the
            -- seven-operation map without a profile-repair key. The runtime
            -- reserve RPC already aliases this internal repair prefix to the
            -- frozen profile-fallback slot; keep admission validation in the
            -- same compatibility contract. Beta policies have an explicit
            -- profile-repair reservation and must not be aliased here.
            IF v_policy.mode = 'test_operation_split'
               AND v_operation_family = 'profile-repair' THEN
                v_policy_slot := v_policy.operation_slot_map ->> 'profile-fallback';
            END IF;
            IF v_policy_slot IS NULL OR v_policy_slot IS DISTINCT FROM p_credential_slot
               OR (v_preflight_order_slot IS NOT NULL
                   AND v_policy_slot IS DISTINCT FROM v_preflight_order_slot) THEN
                RAISE EXCEPTION USING
                    MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
            END IF;
        ELSIF v_preflight_order_slot IS NULL
              AND v_operation_family IN ('relationship-followers', 'relationship-following')
              AND p_credential_slot <> 'secondary' THEN
            -- Ordinary production relationship collection remains secondary
            -- only when no frozen request/preflight contract authorizes a
            -- different slot.
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CREDENTIAL_FORBIDDEN', ERRCODE = 'P0001';
        END IF;
        IF p_logical_provider <> 'apify'
           OR p_provider_claim_token IS DISTINCT FROM p_job_claim_token THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CLAIM_CONFLICT', ERRCODE = 'P0001';
        END IF;
        SELECT provider_run.* INTO v_v2_run
        FROM public.analysis_v2_provider_runs AS provider_run
        WHERE provider_run.request_id = p_request_id
          AND provider_run.job_key = p_job_key
          AND provider_run.operation_key = p_operation_key
        FOR SHARE;
        v_provider_run_found := FOUND;
        IF v_provider_run_found
           AND (v_v2_run.logical_provider IS DISTINCT FROM p_logical_provider
                OR v_v2_run.credential_slot IS DISTINCT FROM p_credential_slot) THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
        END IF;
        RETURN;
    END IF;

    RAISE EXCEPTION USING
        MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CLAIM_CONFLICT', ERRCODE = 'P0001';
END;
$$;

REVOKE ALL ON FUNCTION public.assert_analysis_provider_admission_claim(
    TEXT, TEXT, TEXT, UUID, TEXT, TEXT, UUID, UUID, BIGINT, TIMESTAMPTZ
) FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.analysis_provider_admission_ledger_state(
    p_lease public.analysis_provider_admission_leases
)
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_status TEXT;
    v_logical_provider TEXT;
    v_credential_slot TEXT;
    v_run_id TEXT;
    v_terminalized_at TIMESTAMPTZ;
    v_gemini_state TEXT;
    v_gemini_request_id UUID;
    v_gemini_job_key TEXT;
    v_gemini_attempt INTEGER;
    v_gemini_claim_token UUID;
    v_gemini_fence BIGINT;
    v_attempt INTEGER;
    v_claim_live BOOLEAN := FALSE;
    v_claim_now TIMESTAMPTZ := pg_catalog.clock_timestamp();
BEGIN
    IF p_lease.logical_provider = 'apify'
       AND p_lease.workload_role = 'preflight' THEN
        SELECT provider_run.status, provider_run.logical_provider,
               provider_run.credential_slot, provider_run.run_id,
               provider_run.terminalized_at
        INTO v_status, v_logical_provider, v_credential_slot, v_run_id, v_terminalized_at
        FROM public.analysis_preflight_provider_runs AS provider_run
        WHERE provider_run.preflight_id = p_lease.request_id
          AND provider_run.operation_key = p_lease.operation_key;
    ELSIF p_lease.logical_provider = 'apify'
          AND p_lease.workload_role = 'paid'
          AND p_lease.job_key = 'preflight:provider'
          AND p_lease.operation_key = 'target-profile-fallback' THEN
        -- Betatest preflight-held target profiles execute on the preflight
        -- route while consuming paid capacity. Their authoritative provider
        -- ledger remains the preflight-run table; treating this narrow
        -- identity as a normal V2 run would misclassify a live/ambiguous run
        -- as missing and release paid capacity unsafely.
        SELECT provider_run.status, provider_run.logical_provider,
               provider_run.credential_slot, provider_run.run_id,
               provider_run.terminalized_at
        INTO v_status, v_logical_provider, v_credential_slot, v_run_id, v_terminalized_at
        FROM public.analysis_preflight_provider_runs AS provider_run
        WHERE provider_run.preflight_id = p_lease.request_id
          AND provider_run.operation_key = p_lease.operation_key;
    ELSIF p_lease.logical_provider = 'apify'
          AND p_lease.workload_role = 'paid'
          AND p_lease.job_key = 'paid:target-profile'
          AND p_lease.operation_key ~ '^target-profile-fresh-admission:g([1-9]|[1-9][0-9]|100)$' THEN
        SELECT provider_run.status, provider_run.logical_provider,
               provider_run.credential_slot, provider_run.run_id,
               provider_run.terminalized_at
        INTO v_status, v_logical_provider, v_credential_slot, v_run_id, v_terminalized_at
        FROM public.analysis_preflight_provider_runs AS provider_run
        WHERE provider_run.preflight_id = p_lease.request_id
          AND provider_run.operation_key = p_lease.operation_key;
    ELSIF p_lease.logical_provider = 'apify' AND p_lease.workload_role = 'paid' THEN
        SELECT provider_run.status, provider_run.logical_provider,
               provider_run.credential_slot, provider_run.run_id,
               provider_run.terminalized_at
        INTO v_status, v_logical_provider, v_credential_slot, v_run_id, v_terminalized_at
        FROM public.analysis_v2_provider_runs AS provider_run
        WHERE provider_run.request_id = p_lease.request_id
          AND provider_run.job_key = p_lease.job_key
          AND provider_run.operation_key = p_lease.operation_key;
    ELSIF p_lease.logical_provider = 'gemini' AND p_lease.workload_role = 'paid' THEN
        v_attempt := substring(p_lease.operation_key FROM ':attempt:([0-9]+)$')::INTEGER;
        IF v_attempt IS NULL THEN RETURN 'identity_conflict'; END IF;
        v_gemini_state := NULL;
        SELECT lease.state, lease.request_id, lease.job_key, lease.attempt,
               lease.lease_claim_token, lease.fence
        INTO v_gemini_state, v_gemini_request_id, v_gemini_job_key,
             v_gemini_attempt, v_gemini_claim_token, v_gemini_fence
        FROM public.analysis_v2_gemini_leases AS lease
        WHERE lease.slot = substring(p_lease.credential_slot FROM '^gemini-([1-8])$')::INTEGER;
        IF NOT FOUND THEN RETURN 'missing'; END IF;
        -- A cutoff/reap clears the slot identity but retains its monotonic
        -- fence. Once the slot fence advances, the old admission is safely
        -- fenced out even when the slot is currently available.
        IF v_gemini_state = 'available' THEN
            IF p_lease.provider_fence IS NOT NULL
               AND v_gemini_fence > p_lease.provider_fence THEN
                RETURN 'fenced_out';
            END IF;
            RETURN 'available';
        END IF;
        IF p_lease.provider_fence IS NOT NULL
           AND v_gemini_fence > p_lease.provider_fence
           AND (
               v_gemini_request_id IS DISTINCT FROM p_lease.request_id
               OR v_gemini_job_key IS DISTINCT FROM p_lease.job_key
               OR v_gemini_attempt IS DISTINCT FROM v_attempt
               OR v_gemini_claim_token IS DISTINCT FROM p_lease.claim_token
           ) THEN
            RETURN 'fenced_out';
        END IF;
        IF v_gemini_request_id IS DISTINCT FROM p_lease.request_id
           OR v_gemini_job_key IS DISTINCT FROM p_lease.job_key
           OR v_gemini_attempt IS DISTINCT FROM v_attempt THEN
            RETURN 'identity_conflict';
        END IF;
        IF v_gemini_claim_token IS DISTINCT FROM p_lease.claim_token THEN
            RETURN 'identity_conflict';
        END IF;
        IF p_lease.provider_fence IS NOT NULL
           AND v_gemini_fence IS DISTINCT FROM p_lease.provider_fence THEN
            RETURN 'identity_conflict';
        END IF;
        IF v_gemini_state = 'quarantined' THEN RETURN 'quarantined'; END IF;
        IF v_gemini_state = 'leased' THEN RETURN 'running'; END IF;
        RETURN 'pending';
    ELSE
        RETURN 'identity_conflict';
    END IF;

    IF v_status IS NULL THEN
        -- Admission is acquired before the provider-run reservation. A missing
        -- provider row is only safe to retire when the durable owner that was
        -- authorized to create that row is no longer live. The admission TTL
        -- is intentionally shorter than the job/preflight leases, so checking
        -- only the provider ledger would create a TOCTOU window after a pause:
        -- recovery could release capacity and the still-current worker could
        -- reserve/start the provider afterward.
        IF p_lease.workload_role = 'preflight'
           AND p_lease.logical_provider = 'apify'
           AND p_lease.job_key = 'preflight:provider'
           AND p_lease.operation_key = 'target-profile-fallback' THEN
            SELECT EXISTS (
                SELECT 1
                FROM public.analysis_preflights AS preflight
                WHERE preflight.id = p_lease.request_id
                  AND preflight.status = 'processing'
                  AND preflight.lease_token = p_lease.job_claim_token
                  AND preflight.lease_expires_at IS NOT NULL
                  AND preflight.lease_expires_at > v_claim_now
                  AND preflight.expires_at > v_claim_now
            ) INTO v_claim_live;
        ELSIF p_lease.workload_role = 'paid'
              AND p_lease.logical_provider = 'apify'
              AND p_lease.job_key = 'preflight:provider'
              AND p_lease.operation_key = 'target-profile-fallback' THEN
            -- Betatest preflight-held target profiles keep the preflight
            -- processing lease even though their admission consumes paid
            -- capacity.
            SELECT EXISTS (
                SELECT 1
                FROM public.analysis_preflights AS preflight
                WHERE preflight.id = p_lease.request_id
                  AND preflight.status = 'processing'
                  AND preflight.analysis_entry_channel = 'betatest'
                  AND preflight.lease_token = p_lease.job_claim_token
                  AND preflight.lease_expires_at IS NOT NULL
                  AND preflight.lease_expires_at > v_claim_now
                  AND preflight.expires_at > v_claim_now
            ) INTO v_claim_live;
        ELSIF p_lease.workload_role = 'paid'
              AND p_lease.logical_provider = 'apify'
              AND p_lease.job_key = 'paid:target-profile'
              AND p_lease.operation_key ~ '^target-profile-fresh-admission:g([1-9]|[1-9][0-9]|100)$' THEN
            SELECT EXISTS (
                SELECT 1
                FROM public.analysis_preflights AS preflight
                WHERE preflight.id = p_lease.request_id
                  AND preflight.status = 'ready'
                  AND preflight.admission_status = 'processing'
                  AND preflight.admission_claim_token = p_lease.job_claim_token
                  AND preflight.admission_lease_expires_at IS NOT NULL
                  AND preflight.admission_lease_expires_at > v_claim_now
                  AND preflight.expires_at > v_claim_now
            ) INTO v_claim_live;
        ELSIF p_lease.workload_role = 'paid' THEN
            SELECT EXISTS (
                SELECT 1
                FROM public.analysis_pipeline_jobs AS job
                WHERE job.request_id = p_lease.request_id
                  AND job.job_key = p_lease.job_key
                  AND job.status = 'processing'
                  AND job.lease_token = p_lease.job_claim_token
                  AND job.lease_expires_at IS NOT NULL
                  AND job.lease_expires_at > v_claim_now
            ) INTO v_claim_live;
        END IF;
        IF v_claim_live THEN RETURN 'pending'; END IF;
        RETURN 'missing';
    END IF;
    IF v_logical_provider IS DISTINCT FROM p_lease.logical_provider
       OR v_credential_slot IS DISTINCT FROM p_lease.credential_slot THEN
        RETURN 'identity_conflict';
    END IF;
    IF v_status = 'running' THEN RETURN 'running'; END IF;
    IF v_status IN ('succeeded', 'failed', 'aborted', 'timed_out', 'resolved_no_run', 'rejected')
       AND v_terminalized_at IS NOT NULL THEN
        RETURN 'terminal';
    END IF;
    RETURN 'pending';
END;
$$;

REVOKE ALL ON FUNCTION public.analysis_provider_admission_ledger_state(
    public.analysis_provider_admission_leases
) FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.acquire_analysis_provider_admission(
    p_admission_id TEXT,
    p_workload_role TEXT,
    p_logical_provider TEXT,
    p_credential_slot TEXT,
    p_budget_key TEXT,
    p_request_id UUID,
    p_job_key TEXT,
    p_operation_key TEXT,
    p_job_claim_token UUID,
    p_claim_token UUID,
    p_provider_fence BIGINT,
    p_lease_token UUID,
    p_lease_seconds INTEGER
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_now TIMESTAMPTZ := pg_catalog.clock_timestamp();
    v_expected_id TEXT;
    v_existing public.analysis_provider_admission_leases%ROWTYPE;
    v_budget public.analysis_provider_admission_budgets%ROWTYPE;
    v_budget_found BOOLEAN := FALSE;
    v_global_key TEXT := p_workload_role || ':' || p_logical_provider || ':global';
    v_slot_key TEXT := p_workload_role || ':' || p_logical_provider || ':' || p_credential_slot;
    v_relationship_key TEXT := p_workload_role || ':' || p_logical_provider || ':' || p_credential_slot || ':relationship';
    v_active_count INTEGER;
    v_max_active INTEGER := 0;
    v_rate_limited BOOLEAN := FALSE;
    v_budget_count INTEGER := 0;
    v_required_budget_count INTEGER := 2;
    v_relationship_operation BOOLEAN := p_operation_key LIKE 'relationship-%';
    v_ledger_state TEXT;
    v_reacquire BOOLEAN := FALSE;
    v_identity_lock_key TEXT := p_workload_role || ':' || p_logical_provider || ':'
        || pg_catalog.lower(p_request_id::TEXT) || ':' || p_job_key || ':' || p_operation_key;
BEGIN
    IF p_admission_id IS NULL
       OR p_admission_id !~ '^[0-9a-f]{64}$'
       OR p_workload_role NOT IN ('preflight', 'paid')
       OR p_logical_provider NOT IN ('apify', 'gemini')
       OR p_credential_slot IS NULL
       OR p_credential_slot !~ '^[a-z][a-z0-9_-]{1,31}$'
       OR p_budget_key IS NULL
       OR p_budget_key !~ '^(preflight|paid):(apify|gemini):[a-z0-9:_-]{1,96}$'
       OR p_request_id IS NULL
       OR p_job_key IS NULL
       OR pg_catalog.char_length(p_job_key) NOT BETWEEN 1 AND 160
       OR p_job_key !~ '^[a-z0-9][a-z0-9:._-]{0,159}$'
       OR p_operation_key IS NULL
       OR pg_catalog.char_length(p_operation_key) NOT BETWEEN 1 AND 256
       OR p_operation_key !~ '^[a-z0-9][a-z0-9:._-]{0,255}$'
       OR p_job_claim_token IS NULL
       OR p_claim_token IS NULL
       OR (p_logical_provider = 'gemini' AND (p_provider_fence IS NULL OR p_provider_fence < 1))
       OR (p_logical_provider <> 'gemini' AND p_provider_fence IS NOT NULL)
       OR p_lease_token IS NULL
       OR p_lease_seconds NOT BETWEEN 10 AND 900 THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_INVALID', ERRCODE = 'P0001';
    END IF;

    v_expected_id := public.analysis_provider_admission_expected_id(
        p_workload_role, p_logical_provider, p_credential_slot,
        p_request_id, p_job_key, p_operation_key
    );
    IF p_admission_id IS DISTINCT FROM v_expected_id THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
    END IF;
    IF p_workload_role = 'preflight'
       AND (p_logical_provider <> 'apify'
            OR p_credential_slot NOT IN ('primary', 'quinary', 'senary')) THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CREDENTIAL_FORBIDDEN', ERRCODE = 'P0001';
    END IF;
    IF p_logical_provider = 'gemini'
       AND p_credential_slot !~ '^gemini-[1-8]$' THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CREDENTIAL_FORBIDDEN', ERRCODE = 'P0001';
    END IF;
    IF p_budget_key NOT IN (v_global_key, v_slot_key, v_relationship_key) THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
    END IF;
    IF (v_relationship_operation AND p_budget_key <> v_relationship_key)
       OR (NOT v_relationship_operation AND p_budget_key = v_relationship_key) THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
    END IF;
    IF v_relationship_operation THEN
        v_required_budget_count := 3;
    END IF;

    PERFORM public.assert_analysis_provider_admission_claim(
        p_workload_role,
        p_logical_provider,
        p_credential_slot,
        p_request_id,
        p_job_key,
        p_operation_key,
        p_job_claim_token,
        p_claim_token,
        p_provider_fence,
        v_now
    );

    -- Serialize the durable operation identity before the first existence
    -- check. The admission id deliberately includes credential slot, so a
    -- retry that drifts slot/budget must take the same lock and be classified
    -- before it reaches the alternate-id unique identity constraint.
    PERFORM pg_catalog.pg_advisory_xact_lock(
        pg_catalog.hashtextextended(v_identity_lock_key, 0)
    );

    SELECT lease.* INTO v_existing
    FROM public.analysis_provider_admission_leases AS lease
    WHERE lease.workload_role = p_workload_role
      AND lease.logical_provider = p_logical_provider
      AND lease.request_id = p_request_id
      AND lease.job_key = p_job_key
      AND lease.operation_key = p_operation_key
      AND lease.admission_id IS DISTINCT FROM p_admission_id
    FOR UPDATE;
    IF FOUND THEN
        RAISE EXCEPTION USING
            MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
    END IF;

    -- Keep a second id lock for unrelated operation identities that happen to
    -- hash to the same durable-operation lock and for exact-id replay.
    PERFORM pg_catalog.pg_advisory_xact_lock(
        pg_catalog.hashtextextended(p_admission_id, 0)
    );

    SELECT lease.* INTO v_existing
    FROM public.analysis_provider_admission_leases AS lease
    WHERE lease.admission_id = p_admission_id
    FOR UPDATE;
    IF FOUND THEN
        IF v_existing.workload_role IS DISTINCT FROM p_workload_role
           OR v_existing.logical_provider IS DISTINCT FROM p_logical_provider
           OR v_existing.credential_slot IS DISTINCT FROM p_credential_slot
           OR v_existing.budget_key IS DISTINCT FROM p_budget_key
           OR v_existing.request_id IS DISTINCT FROM p_request_id
           OR v_existing.job_key IS DISTINCT FROM p_job_key
           OR v_existing.operation_key IS DISTINCT FROM p_operation_key THEN
            RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
        END IF;
        IF v_existing.state = 'leased' AND v_existing.expires_at > v_now THEN
            -- A durable operation can keep the same provider fence while the
            -- queue worker claim rotates. Both claims are ownership, so any
            -- change is a takeover and must be backed by an already-running
            -- provider ledger before rotating this admission's secret/fence.
            IF v_existing.claim_token IS DISTINCT FROM p_claim_token
               OR v_existing.job_claim_token IS DISTINCT FROM p_job_claim_token THEN
                -- A takeover may only adopt an already-running provider row. A
                -- fresh/start-ambiguous row remains owned by its original claim.
                v_ledger_state := public.analysis_provider_admission_ledger_state(v_existing);
                IF v_ledger_state <> 'running' THEN
                    RAISE EXCEPTION USING
                        MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CLAIM_CONFLICT', ERRCODE = 'P0001';
                END IF;
                UPDATE public.analysis_provider_admission_leases AS lease
                SET claim_token = p_claim_token,
                    job_claim_token = p_job_claim_token,
                    provider_fence = p_provider_fence,
                    lease_token = p_lease_token,
                    fence = lease.fence + 1,
                    updated_at = v_now
                WHERE lease.admission_id = p_admission_id
                  AND lease.state = 'leased'
                  AND lease.expires_at > v_now
                RETURNING lease.* INTO v_existing;
                IF NOT FOUND THEN
                    RAISE EXCEPTION USING
                        MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_FENCE_MISMATCH', ERRCODE = 'P0001';
                END IF;
                SELECT pg_catalog.count(*)::INTEGER INTO v_active_count
                FROM public.analysis_provider_admission_leases AS lease
                WHERE lease.state IN ('leased', 'recovery_required')
                  AND lease.workload_role = p_workload_role
                  AND lease.logical_provider = p_logical_provider;
                SELECT budget.max_active INTO v_max_active
                FROM public.analysis_provider_admission_budgets AS budget
                WHERE budget.budget_key = p_budget_key;
                RETURN public.analysis_provider_admission_json(
                    v_existing, 'adopted', v_active_count, COALESCE(v_max_active, 1),
                    p_job_claim_token, p_claim_token
                );
            END IF;
            SELECT pg_catalog.count(*)::INTEGER INTO v_active_count
            FROM public.analysis_provider_admission_leases AS lease
            WHERE lease.state IN ('leased', 'recovery_required')
              AND lease.workload_role = p_workload_role
              AND lease.logical_provider = p_logical_provider;
            SELECT budget.max_active INTO v_max_active
            FROM public.analysis_provider_admission_budgets AS budget
            WHERE budget.budget_key = p_budget_key;
            RETURN public.analysis_provider_admission_json(
                v_existing, 'already_acquired', v_active_count, COALESCE(v_max_active, 1),
                p_job_claim_token, p_claim_token
            );
        END IF;
        IF v_existing.state = 'leased' THEN
            RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CAPACITY_PENDING', ERRCODE = 'P0001';
        END IF;
        IF v_existing.state = 'recovery_required' THEN
            -- Expiry does not prove that the provider stopped. A recovery pass
            -- may hand the same operation to a live durable task only after the
            -- provider ledger proves that the external run is still running.
            v_ledger_state := public.analysis_provider_admission_ledger_state(v_existing);
            IF v_ledger_state = 'running' THEN
                UPDATE public.analysis_provider_admission_leases AS lease
                SET state = 'leased',
                    claim_token = p_claim_token,
                    job_claim_token = p_job_claim_token,
                    provider_fence = p_provider_fence,
                    lease_token = p_lease_token,
                    fence = lease.fence + 1,
                    acquired_at = v_now,
                    expires_at = v_now + (p_lease_seconds || ' seconds')::INTERVAL,
                    recovered_at = NULL,
                    release_reason = NULL,
                    resolution_source = NULL,
                    resolution_token_hash = NULL,
                    updated_at = v_now
                WHERE lease.admission_id = p_admission_id
                  AND lease.state = 'recovery_required'
                RETURNING lease.* INTO v_existing;
                IF NOT FOUND THEN
                    RAISE EXCEPTION USING
                        MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_FENCE_MISMATCH', ERRCODE = 'P0001';
                END IF;
                SELECT pg_catalog.count(*)::INTEGER INTO v_active_count
                FROM public.analysis_provider_admission_leases AS lease
                WHERE lease.state IN ('leased', 'recovery_required')
                  AND lease.workload_role = p_workload_role
                  AND lease.logical_provider = p_logical_provider;
                SELECT budget.max_active INTO v_max_active
                FROM public.analysis_provider_admission_budgets AS budget
                WHERE budget.budget_key = p_budget_key;
                RETURN public.analysis_provider_admission_json(
                    v_existing, 'adopted', v_active_count, COALESCE(v_max_active, 1),
                    p_job_claim_token, p_claim_token
                );
            END IF;
            -- Terminal/available/quarantined states are released by the
            -- resolver, never by an acquire retry. Pending and identity
            -- conflicts retain the row and therefore retain capacity.
            IF v_ledger_state = 'identity_conflict' THEN
                RAISE EXCEPTION USING
                    MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
            END IF;
            RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CAPACITY_PENDING', ERRCODE = 'P0001';
        END IF;
        IF v_existing.state = 'released' AND v_existing.release_reason = 'prestart_rejected' THEN
            v_ledger_state := public.analysis_provider_admission_ledger_state(v_existing);
            IF v_ledger_state NOT IN ('terminal', 'missing') THEN
                RAISE EXCEPTION USING
                    MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CLAIM_CONFLICT', ERRCODE = 'P0001';
            END IF;
            v_reacquire := TRUE;
        ELSE
            -- Terminal release rows are intentionally not reusable: their
            -- provider ledger may already contain a charged run.
            RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
        END IF;
    END IF;

    -- Lock all budgets used by the role/provider in lexical order. Every caller uses
    -- this order, so concurrent slot/global claims cannot deadlock each other.
    FOR v_budget IN
        SELECT budget.*
        FROM public.analysis_provider_admission_budgets AS budget
        WHERE budget.budget_key IN (p_budget_key, v_global_key, v_slot_key)
           OR (v_relationship_operation AND budget.budget_key = v_relationship_key)
        ORDER BY budget.budget_key
        FOR UPDATE
    LOOP
        v_budget_count := v_budget_count + 1;
        IF v_budget.workload_role IS DISTINCT FROM p_workload_role
           OR v_budget.logical_provider IS DISTINCT FROM p_logical_provider
           OR (
               v_budget.budget_key = p_budget_key
               AND v_budget.credential_slot IS DISTINCT FROM
                   CASE WHEN v_budget.budget_key = v_global_key THEN NULL ELSE p_credential_slot END
           ) THEN
            RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
        END IF;
        v_budget_found := v_budget_found OR v_budget.budget_key = p_budget_key;
        v_max_active := CASE
            WHEN v_budget.budget_key = p_budget_key THEN v_budget.max_active
            ELSE v_max_active
        END;
        SELECT pg_catalog.count(*)::INTEGER INTO v_active_count
        FROM public.analysis_provider_admission_leases AS lease
        WHERE lease.state IN ('leased', 'recovery_required')
          AND lease.workload_role = v_budget.workload_role
          AND lease.logical_provider = v_budget.logical_provider
          AND (
              v_budget.credential_slot IS NULL
              OR lease.credential_slot = v_budget.credential_slot
          )
          AND (
              v_budget.budget_key NOT LIKE '%:relationship'
              OR lease.operation_key LIKE 'relationship-%'
          );
        IF v_active_count >= v_budget.max_active THEN
            RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CAPACITY_PENDING', ERRCODE = 'P0001';
        END IF;
        IF v_budget.window_started_at + INTERVAL '1 minute' <= v_now THEN
            UPDATE public.analysis_provider_admission_budgets AS budget
            SET window_started_at = v_now, window_count = 0, updated_at = v_now
            WHERE budget.budget_key = v_budget.budget_key;
            v_budget.window_count := 0;
        END IF;
        IF v_budget.window_count >= v_budget.rate_limit_per_minute THEN
            v_rate_limited := TRUE;
        END IF;
    END LOOP;
    IF v_budget_count < v_required_budget_count OR NOT v_budget_found OR v_rate_limited THEN
        IF v_budget_count < v_required_budget_count OR NOT v_budget_found THEN
            RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_BUDGET_NOT_FOUND', ERRCODE = 'P0001';
        END IF;
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CAPACITY_PENDING', ERRCODE = 'P0001';
    END IF;

    FOR v_budget IN
        SELECT budget.*
        FROM public.analysis_provider_admission_budgets AS budget
        WHERE budget.budget_key IN (p_budget_key, v_global_key, v_slot_key)
           OR (v_relationship_operation AND budget.budget_key = v_relationship_key)
        ORDER BY budget.budget_key
        FOR UPDATE
    LOOP
        UPDATE public.analysis_provider_admission_budgets AS budget
        SET window_count = budget.window_count + 1, updated_at = v_now
        WHERE budget.budget_key = v_budget.budget_key;
    END LOOP;

    IF v_reacquire THEN
        UPDATE public.analysis_provider_admission_leases AS lease
        SET state = 'leased',
                    claim_token = p_claim_token,
                    job_claim_token = p_job_claim_token,
                    provider_fence = p_provider_fence,
            lease_token = p_lease_token,
            fence = lease.fence + 1,
            acquired_at = v_now,
            expires_at = v_now + (p_lease_seconds || ' seconds')::INTERVAL,
            released_at = NULL,
            recovered_at = NULL,
            release_reason = NULL,
            resolution_source = NULL,
            resolution_token_hash = NULL,
            updated_at = v_now
        WHERE lease.admission_id = p_admission_id
          AND lease.state = 'released'
          AND lease.release_reason = 'prestart_rejected'
        RETURNING lease.* INTO v_existing;
        IF NOT FOUND THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_FENCE_MISMATCH', ERRCODE = 'P0001';
        END IF;
    ELSE
        INSERT INTO public.analysis_provider_admission_leases (
        admission_id, workload_role, logical_provider, credential_slot, budget_key,
            request_id, job_key, operation_key, claim_token, job_claim_token,
            provider_fence,
            lease_token, fence,
        acquired_at, expires_at, created_at, updated_at
        ) VALUES (
        p_admission_id, p_workload_role, p_logical_provider, p_credential_slot, p_budget_key,
        p_request_id, p_job_key, p_operation_key, p_claim_token, p_job_claim_token,
        p_provider_fence,
        p_lease_token, 1,
        v_now, v_now + (p_lease_seconds || ' seconds')::INTERVAL, v_now, v_now
        )
        RETURNING * INTO v_existing;
    END IF;

    SELECT pg_catalog.count(*)::INTEGER INTO v_active_count
    FROM public.analysis_provider_admission_leases AS lease
    WHERE lease.state IN ('leased', 'recovery_required')
      AND lease.workload_role = p_workload_role
      AND lease.logical_provider = p_logical_provider;
    RETURN public.analysis_provider_admission_json(
        v_existing, 'acquired', v_active_count, COALESCE(v_max_active, 1),
        p_job_claim_token, p_claim_token
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.renew_analysis_provider_admission(
    p_admission_id TEXT,
    p_lease_token UUID,
    p_fence BIGINT,
    p_lease_seconds INTEGER
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_now TIMESTAMPTZ := pg_catalog.clock_timestamp();
    v_expires TIMESTAMPTZ;
    v_lease public.analysis_provider_admission_leases%ROWTYPE;
BEGIN
    IF p_admission_id IS NULL OR p_admission_id !~ '^[0-9a-f]{64}$'
       OR p_lease_token IS NULL OR p_fence IS NULL
       OR p_lease_seconds NOT BETWEEN 10 AND 900 THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_INVALID', ERRCODE = 'P0001';
    END IF;
    SELECT lease.* INTO v_lease
    FROM public.analysis_provider_admission_leases AS lease
    WHERE lease.admission_id = p_admission_id
      AND lease.state = 'leased'
      AND lease.lease_token = p_lease_token
      AND lease.fence = p_fence
      AND lease.expires_at > v_now
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_FENCE_MISMATCH', ERRCODE = 'P0001';
    END IF;
    -- Renewal is an ownership operation, not merely a lease-token heartbeat.
    -- Re-run the immutable lineage and live-owner checks so a leaked timer
    -- cannot extend an admission after the preflight/job/Gemini claim rotates
    -- or expires.  Takeover/adoption remains the only path that can install a
    -- new claim and fence after a durable running-ledger proof.
    PERFORM public.assert_analysis_provider_admission_claim(
        v_lease.workload_role,
        v_lease.logical_provider,
        v_lease.credential_slot,
        v_lease.request_id,
        v_lease.job_key,
        v_lease.operation_key,
        v_lease.job_claim_token,
        v_lease.claim_token,
        v_lease.provider_fence,
        v_now
    );
    v_expires := v_now + (p_lease_seconds || ' seconds')::INTERVAL;
    UPDATE public.analysis_provider_admission_leases AS lease
    SET expires_at = v_expires, updated_at = v_now
    WHERE lease.admission_id = p_admission_id;
    RETURN pg_catalog.jsonb_build_object(
        'renewed', TRUE, 'fence', v_lease.fence, 'expiresAt', v_expires
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.release_analysis_provider_admission(
    p_admission_id TEXT,
    p_lease_token UUID,
    p_fence BIGINT,
    p_release_reason TEXT DEFAULT 'terminal'
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_now TIMESTAMPTZ := pg_catalog.clock_timestamp();
    v_lease public.analysis_provider_admission_leases%ROWTYPE;
    v_ledger_state TEXT;
BEGIN
    IF p_admission_id IS NULL OR p_admission_id !~ '^[0-9a-f]{64}$'
       OR p_lease_token IS NULL OR p_fence IS NULL THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_INVALID', ERRCODE = 'P0001';
    END IF;
    IF p_release_reason NOT IN ('terminal', 'prestart_rejected') THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_INVALID', ERRCODE = 'P0001';
    END IF;
    SELECT lease.* INTO v_lease
    FROM public.analysis_provider_admission_leases AS lease
    WHERE lease.admission_id = p_admission_id
      AND lease.lease_token = p_lease_token
      AND lease.fence = p_fence
    FOR UPDATE;
    IF NOT FOUND OR v_lease.state = 'recovery_required' THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_FENCE_MISMATCH', ERRCODE = 'P0001';
    END IF;
    IF v_lease.state = 'released' THEN
        RETURN pg_catalog.jsonb_build_object('released', TRUE);
    END IF;
    -- A Gemini slot may have been reused after this admission expired. Its
    -- provider claim token is distinct from the job token and must still fence
    -- release; otherwise a stale worker could free a newer slot's admission.
    IF v_lease.logical_provider = 'gemini' THEN
        v_ledger_state := public.analysis_provider_admission_ledger_state(v_lease);
        IF v_ledger_state IN ('identity_conflict', 'fenced_out', 'missing') THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
        END IF;
    ELSIF v_lease.logical_provider = 'apify' THEN
        -- The provider-run row is reserved immediately after admission and
        -- must be terminal before a live lease can be released.  A missing
        -- row is the one safe exception: the mandatory sequencing proves no
        -- external provider start was possible.
        v_ledger_state := public.analysis_provider_admission_ledger_state(v_lease);
        IF v_ledger_state = 'identity_conflict' THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
        END IF;
        IF v_ledger_state NOT IN ('terminal', 'missing') THEN
            RAISE EXCEPTION USING
                MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_CLAIM_CONFLICT', ERRCODE = 'P0001';
        END IF;
    END IF;
    UPDATE public.analysis_provider_admission_leases AS lease
    SET state = 'released', released_at = v_now, expires_at = v_now,
        release_reason = p_release_reason,
        updated_at = v_now
    WHERE lease.admission_id = p_admission_id;
    RETURN pg_catalog.jsonb_build_object('released', TRUE);
END;
$$;

CREATE OR REPLACE FUNCTION public.recover_expired_analysis_provider_admission(
    p_admission_id TEXT,
    p_recovery_token UUID
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_now TIMESTAMPTZ := pg_catalog.clock_timestamp();
    v_current public.analysis_provider_admission_leases%ROWTYPE;
BEGIN
    IF p_admission_id IS NULL OR p_admission_id !~ '^[0-9a-f]{64}$'
       OR p_recovery_token IS NULL THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_INVALID', ERRCODE = 'P0001';
    END IF;
    SELECT lease.* INTO v_current
    FROM public.analysis_provider_admission_leases AS lease
    WHERE lease.admission_id = p_admission_id
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_NOT_FOUND', ERRCODE = 'P0001';
    END IF;
    IF v_current.state = 'recovery_required' THEN
        RETURN pg_catalog.jsonb_build_object('recovered', TRUE);
    END IF;
    IF v_current.state <> 'leased' OR v_current.expires_at > v_now THEN
        RETURN pg_catalog.jsonb_build_object('recovered', FALSE);
    END IF;
    UPDATE public.analysis_provider_admission_leases AS lease
    SET state = 'recovery_required', lease_token = p_recovery_token,
        fence = lease.fence + 1, expires_at = v_now,
        recovered_at = v_now, release_reason = NULL,
        resolution_source = NULL, resolution_token_hash = NULL,
        updated_at = v_now
    WHERE lease.admission_id = p_admission_id;
    RETURN pg_catalog.jsonb_build_object('recovered', TRUE);
END;
$$;

CREATE OR REPLACE FUNCTION public.resolve_analysis_provider_admission(
    p_admission_id TEXT,
    p_resolution_token UUID
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_now TIMESTAMPTZ := pg_catalog.clock_timestamp();
    v_lease public.analysis_provider_admission_leases%ROWTYPE;
    v_ledger_state TEXT;
    v_source TEXT;
BEGIN
    IF p_admission_id IS NULL OR p_admission_id !~ '^[0-9a-f]{64}$'
       OR p_resolution_token IS NULL THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_INVALID', ERRCODE = 'P0001';
    END IF;
    SELECT lease.* INTO v_lease
    FROM public.analysis_provider_admission_leases AS lease
    WHERE lease.admission_id = p_admission_id
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_NOT_FOUND', ERRCODE = 'P0001';
    END IF;
    IF v_lease.state = 'released' THEN
        RETURN pg_catalog.jsonb_build_object('resolved', FALSE);
    END IF;
    IF v_lease.state <> 'recovery_required' THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_RESOLUTION_PENDING', ERRCODE = 'P0001';
    END IF;

    v_ledger_state := public.analysis_provider_admission_ledger_state(v_lease);
    IF v_ledger_state = 'identity_conflict' THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
    END IF;
    IF v_ledger_state = 'fenced_out' THEN
        IF v_lease.logical_provider <> 'gemini' THEN
            RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
        END IF;
        v_source := 'gemini_lease_fenced';
    ELSIF v_ledger_state = 'missing' THEN
        -- Admission is acquired before the provider-run reserve callback.  An
        -- expired Apify row with no provider ledger therefore proves that no
        -- external start occurred and may be retired safely.  Gemini missing
        -- rows remain ambiguous because the slot fence is authoritative.
        IF v_lease.logical_provider <> 'apify' THEN
            RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_IDENTITY_CONFLICT', ERRCODE = 'P0001';
        END IF;
        v_source := 'provider_ledger_absent';
    ELSIF v_ledger_state NOT IN ('terminal', 'available', 'quarantined') THEN
        RETURN pg_catalog.jsonb_build_object('resolved', FALSE);
    ELSE
        v_source := CASE
            WHEN v_lease.logical_provider = 'gemini' THEN 'gemini_lease_fenced'
            ELSE 'provider_ledger_terminal'
        END;
    END IF;
    UPDATE public.analysis_provider_admission_leases AS lease
    SET state = 'released', released_at = v_now,
        release_reason = 'ledger_resolved',
        resolution_source = v_source,
        resolution_token_hash = pg_catalog.encode(
            extensions.digest(
                pg_catalog.convert_to(p_resolution_token::TEXT, 'UTF8'), 'sha256'
            ), 'hex'
        ),
        updated_at = v_now
    WHERE lease.admission_id = p_admission_id
      AND lease.state = 'recovery_required';
    RETURN pg_catalog.jsonb_build_object('resolved', TRUE);
END;
$$;

CREATE OR REPLACE FUNCTION public.list_expired_analysis_provider_admissions(
