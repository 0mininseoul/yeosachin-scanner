CREATE OR REPLACE FUNCTION public.analysis_provider_admission_expected_id(
    p_workload_role TEXT,
    p_logical_provider TEXT,
    p_credential_slot TEXT,
    p_request_id UUID,
    p_job_key TEXT,
    p_operation_key TEXT
)
RETURNS TEXT
LANGUAGE SQL
IMMUTABLE
SET search_path = ''
AS $$
    SELECT pg_catalog.encode(
        extensions.digest(
            pg_catalog.convert_to(
                'analysis-provider-admission-v1' || E'\n'
                || p_workload_role || E'\n'
                || p_logical_provider || E'\n'
                || p_credential_slot || E'\n'
                || pg_catalog.lower(p_request_id::TEXT) || E'\n'
                || p_job_key || E'\n'
                || p_operation_key,
                'UTF8'
            ),
            'sha256'
        ),
        'hex'
    )
$$;

