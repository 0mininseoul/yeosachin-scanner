-- B-lite task exhaustion recovery.  The original dispatch table predates the capacity
-- admission rollout and only had a single deterministic task name.  Keep that legacy task
-- readable, while new dispatches carry an explicit generation and the last successfully
-- enqueued token.  Rearm rotates both under the same row fence before a successor task is
-- created, so a max-attempts-exhausted delivery cannot strand a pending cache row.
ALTER TABLE public.precheckout_blite_dispatches
    ADD COLUMN IF NOT EXISTS dispatch_generation INTEGER NOT NULL DEFAULT 1,
    ADD COLUMN IF NOT EXISTS last_dispatch_token UUID;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_catalog.pg_constraint
        WHERE conrelid = 'public.precheckout_blite_dispatches'::pg_catalog.regclass
          AND conname = 'precheckout_blite_dispatch_generation_check'
    ) THEN
        ALTER TABLE public.precheckout_blite_dispatches
            ADD CONSTRAINT precheckout_blite_dispatch_generation_check
            CHECK (dispatch_generation BETWEEN 1 AND 100);
    END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS precheckout_blite_dispatch_rearm_idx
    ON public.precheckout_blite_dispatches (state, updated_at, dispatch_generation)
    WHERE state IN ('enqueued', 'enqueuing');

CREATE OR REPLACE FUNCTION public.reserve_precheckout_blite_dispatch_v1(p_preflight_id UUID)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_now TIMESTAMPTZ := pg_catalog.clock_timestamp();
    v_token UUID := extensions.gen_random_uuid();
    v_preflight public.analysis_preflights%ROWTYPE;
    v_dispatch public.precheckout_blite_dispatches%ROWTYPE;
    v_generation INTEGER;
BEGIN
    IF p_preflight_id IS NULL THEN
        RAISE EXCEPTION USING MESSAGE = 'PRECHECKOUT_BLITE_DISPATCH_INVALID', ERRCODE = 'P0001';
    END IF;
    SELECT preflight.* INTO v_preflight
    FROM public.analysis_preflights AS preflight
    WHERE preflight.id = p_preflight_id
    FOR UPDATE;
    v_now := pg_catalog.clock_timestamp();
    IF NOT FOUND THEN
        RETURN pg_catalog.jsonb_build_object(
            'should_enqueue', FALSE, 'dispatch_token', NULL, 'dispatch_generation', 1
        );
    END IF;
    IF v_preflight.precheckout_blite_cohort IS DISTINCT FROM TRUE
       OR v_preflight.status IS DISTINCT FROM 'ready'
       OR v_preflight.pii_scrubbed_at IS NOT NULL
       OR v_preflight.expires_at <= v_now
       OR NOT EXISTS (
            SELECT 1 FROM public.precheckout_blite_sources AS source
            WHERE source.preflight_id = p_preflight_id
       )
       OR NOT EXISTS (
            SELECT 1 FROM public.precheckout_blite_cache AS cache
            WHERE cache.preflight_id = p_preflight_id
              AND cache.state = 'pending'
       ) THEN
        RETURN pg_catalog.jsonb_build_object(
            'should_enqueue', FALSE, 'dispatch_token', NULL, 'dispatch_generation', 1
        );
    END IF;

    SELECT dispatch.* INTO v_dispatch
    FROM public.precheckout_blite_dispatches AS dispatch
    WHERE dispatch.preflight_id = p_preflight_id
    FOR UPDATE;
    IF NOT FOUND THEN
        INSERT INTO public.precheckout_blite_dispatches (
            preflight_id, state, attempt_count, dispatch_generation, created_at, updated_at
        ) VALUES (p_preflight_id, 'idle', 0, 1, v_now, v_now)
        RETURNING * INTO v_dispatch;
    END IF;

    v_now := pg_catalog.clock_timestamp();
    IF v_dispatch.state = 'enqueued' THEN
        RETURN pg_catalog.jsonb_build_object(
            'should_enqueue', FALSE,
            'dispatch_token', NULL,
            'dispatch_generation', v_dispatch.dispatch_generation
        );
    END IF;
    IF v_dispatch.state = 'enqueuing'
       AND v_dispatch.lease_expires_at > v_now THEN
        RETURN pg_catalog.jsonb_build_object(
            'should_enqueue', FALSE,
            'dispatch_token', NULL,
            'dispatch_generation', v_dispatch.dispatch_generation
        );
    END IF;

    v_generation := CASE
        WHEN v_dispatch.attempt_count = 0 THEN v_dispatch.dispatch_generation
        ELSE v_dispatch.dispatch_generation + 1
    END;
    IF v_generation > 100 THEN
        RAISE EXCEPTION USING MESSAGE = 'PRECHECKOUT_BLITE_DISPATCH_GENERATION_EXHAUSTED', ERRCODE = 'P0001';
    END IF;
    UPDATE public.precheckout_blite_dispatches
    SET state = 'enqueuing',
        attempt_count = v_dispatch.attempt_count + 1,
        dispatch_generation = v_generation,
        dispatch_token = v_token,
        last_dispatch_token = NULL,
        lease_expires_at = v_now + INTERVAL '2 minutes',
        failure_reason = NULL,
        updated_at = v_now
    WHERE preflight_id = p_preflight_id;
    RETURN pg_catalog.jsonb_build_object(
        'should_enqueue', TRUE,
        'dispatch_token', v_token,
        'dispatch_generation', v_generation
    );
END;
$$;

