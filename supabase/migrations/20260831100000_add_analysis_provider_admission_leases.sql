-- Keyset pagination prevents expired leases that cannot yet be resolved
-- (running/ambiguous provider ledgers) from monopolizing every maintenance
-- page. The cursor is an immutable (expires_at, fence, admission_id) key, so
-- page two remains reachable even when page one is unchanged across passes.
-- A caller may stop at its hard work limit and resume from nextCursor later.
CREATE OR REPLACE FUNCTION public.list_expired_analysis_provider_admissions_page(
    p_limit INTEGER DEFAULT 16,
    p_after_expires_at TIMESTAMPTZ DEFAULT NULL,
    p_after_fence BIGINT DEFAULT NULL,
    p_after_admission_id TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_now TIMESTAMPTZ := pg_catalog.clock_timestamp();
BEGIN
    IF p_limit IS NULL OR p_limit NOT BETWEEN 1 AND 64
       OR ((p_after_expires_at IS NULL OR p_after_fence IS NULL OR p_after_admission_id IS NULL)
           AND NOT (p_after_expires_at IS NULL AND p_after_fence IS NULL AND p_after_admission_id IS NULL))
       OR (p_after_admission_id IS NOT NULL
           AND p_after_admission_id !~ '^[0-9a-f]{64}$') THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_PROVIDER_ADMISSION_INVALID', ERRCODE = 'P0001';
    END IF;
    RETURN (
        WITH eligible AS (
            SELECT lease.admission_id, lease.fence, lease.expires_at
            FROM public.analysis_provider_admission_leases AS lease
            WHERE lease.state IN ('leased', 'recovery_required')
              AND lease.expires_at <= v_now
              AND (
                    p_after_expires_at IS NULL
                    OR (lease.expires_at, lease.fence, lease.admission_id)
                       > (p_after_expires_at, p_after_fence, p_after_admission_id)
              )
            ORDER BY lease.expires_at, lease.fence, lease.admission_id
            LIMIT p_limit + 1
        ), page AS (
            SELECT eligible.admission_id, eligible.fence, eligible.expires_at
            FROM eligible
            ORDER BY eligible.expires_at, eligible.fence, eligible.admission_id
            LIMIT p_limit
        ), overflow AS (
            SELECT count(*) > p_limit AS has_more
            FROM eligible
        ), next_cursor AS (
            SELECT page.expires_at, page.fence, page.admission_id
            FROM page
            ORDER BY page.expires_at DESC, page.fence DESC, page.admission_id DESC
            LIMIT 1
        )
        SELECT pg_catalog.jsonb_build_object(
            'candidates', COALESCE(
                (
                    SELECT pg_catalog.jsonb_agg(
                        pg_catalog.jsonb_build_object(
                            'admissionId', page.admission_id,
                            'fence', page.fence,
                            'expiresAt', page.expires_at
                        )
                        ORDER BY page.expires_at, page.fence, page.admission_id
                    )
                    FROM page
                ),
                '[]'::jsonb
            ),
            'hasMore', (SELECT overflow.has_more FROM overflow),
            'nextCursor', CASE
                WHEN (SELECT overflow.has_more FROM overflow) THEN (
                    SELECT pg_catalog.jsonb_build_object(
                        'expiresAt', next_cursor.expires_at,
                        'fence', next_cursor.fence,
                        'admissionId', next_cursor.admission_id
                    )
                    FROM next_cursor
                )
                ELSE NULL
            END
        )
    );
END;
$$;

-- Gate activation only after the old, admission-bypassing provider surfaces
-- are quiet and the queues/tasks holding old work have drained.  This is
-- intentionally a service-role-only observation RPC: it returns counts and
-- no request, user, provider-input, or credential data.  The deploy wrapper
-- calls it before promotion of an active no-traffic revision, after the
-- operator has frozen producers, paused old queues/targets, and verified the
-- exact serving revision.  Bootstrap (gates off) does not call this barrier.
CREATE OR REPLACE FUNCTION public.analysis_capacity_activation_readiness()
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_now TIMESTAMPTZ := pg_catalog.clock_timestamp();
    v_legacy_active_provider_runs BIGINT;
    v_legacy_active_preflight_runs BIGINT;
    v_legacy_active_profile_repair_runs BIGINT;
    v_legacy_active_v1_provider_runs BIGINT;
    v_legacy_active_processing_claims BIGINT;
    v_legacy_active_v2_job_claims BIGINT;
    v_legacy_active_profile_provider_canary_runs BIGINT;
    v_legacy_active_old_target_invocations BIGINT;
    v_legacy_active_queued_preflight_tasks BIGINT;
    v_legacy_active_queued_v2_tasks BIGINT;
    v_legacy_active_fresh_admissions BIGINT;
    v_legacy_active_beta_prepare BIGINT;
    v_unreconciled_provider_runs BIGINT;
    v_unreconciled_preflight_runs BIGINT;
    v_unreconciled_profile_repair_runs BIGINT;
    v_unreconciled_v1_provider_runs BIGINT;
    v_unreconciled_profile_provider_canary_runs BIGINT;
BEGIN
    -- A provider ledger is safe only when its exact durable admission is still
    -- active.  Healthy role-aware traffic therefore does not block promotion;
    -- an unadmitted, expired, or identity-drifted run does.
    SELECT pg_catalog.count(*)
    INTO v_legacy_active_provider_runs
    FROM public.analysis_v2_provider_runs AS provider_run
    WHERE provider_run.status IN ('starting', 'running')
      AND NOT EXISTS (
          SELECT 1
          FROM public.analysis_provider_admission_leases AS admission
          WHERE admission.workload_role = 'paid'
            AND admission.logical_provider = provider_run.logical_provider
            AND admission.request_id = provider_run.request_id
            AND admission.job_key = provider_run.job_key
            AND admission.operation_key = provider_run.operation_key
            AND admission.credential_slot = provider_run.credential_slot
            AND admission.job_claim_token = provider_run.job_claim_token
            AND admission.state IN ('leased', 'recovery_required')
            AND admission.expires_at > v_now
      );

    -- Ordinary preflight, the narrowly validated beta paid branch, and fresh
    -- paid admission all use this ledger.  A live row with a matching active
    -- admission is safe; a starting/running row without one is a legacy start.
    SELECT pg_catalog.count(*)
    INTO v_legacy_active_preflight_runs
    FROM public.analysis_preflight_provider_runs AS provider_run
    WHERE provider_run.status IN ('starting', 'running')
      AND NOT EXISTS (
          SELECT 1
          FROM public.analysis_provider_admission_leases AS admission
          WHERE admission.logical_provider = 'apify'
            AND admission.request_id = provider_run.preflight_id
            AND admission.credential_slot = provider_run.credential_slot
            AND admission.state IN ('leased', 'recovery_required')
            AND admission.expires_at > v_now
            AND (
                (
                    admission.workload_role = 'preflight'
                    AND admission.job_key = 'preflight:provider'
                    AND admission.operation_key = 'target-profile-fallback'
                    AND provider_run.operation_key = 'target-profile-fallback'
                )
                OR (
                    admission.workload_role = 'paid'
                    AND admission.job_key = 'preflight:provider'
                    AND admission.operation_key = 'target-profile-fallback'
                    AND provider_run.operation_key = 'target-profile-fallback'
                )
                OR (
                    admission.workload_role = 'paid'
                    AND admission.job_key = 'paid:target-profile'
                    AND admission.operation_key ~ '^target-profile-fresh-admission:g([1-9]|[1-9][0-9]|100)$'
                    AND provider_run.operation_key = admission.operation_key
                )
            )
      );

    SELECT pg_catalog.count(*)
    INTO v_legacy_active_profile_repair_runs
    FROM public.analysis_v2_profile_repair_canary_runs AS canary_run
    WHERE canary_run.state IN ('starting', 'running', 'ambiguous');

    SELECT pg_catalog.count(*)
    INTO v_legacy_active_profile_provider_canary_runs
    FROM public.analysis_v2_profile_provider_canary_runs AS canary_run
    WHERE canary_run.state IN ('starting', 'running', 'ambiguous');

    -- The V1 table intentionally has no terminal state; all rows are live
    -- provider intents and must be drained before an active gate-on revision.
    SELECT pg_catalog.count(*)
    INTO v_legacy_active_v1_provider_runs
    FROM public.analysis_provider_runs AS provider_run
    WHERE provider_run.status IN ('starting', 'running');

    -- Live V1 claims and unsafe preflight claims are separate from healthy
    -- role-aware ordinary traffic. Expired claims cannot create a provider and
    -- are left for normal maintenance recovery.
    SELECT pg_catalog.count(*)
    INTO v_legacy_active_processing_claims
    FROM (
        SELECT request.id
        FROM public.analysis_requests AS request
        WHERE request.pipeline_version IS DISTINCT FROM 'v2'
          AND request.status IN ('pending', 'processing')
          AND request.processing_lease_token IS NOT NULL
          AND request.processing_lease_expires_at > v_now
        UNION ALL
        SELECT preflight.id
        FROM public.analysis_preflights AS preflight
        WHERE preflight.status = 'processing'
          AND preflight.lease_token IS NOT NULL
          AND preflight.lease_expires_at > v_now
          AND (
              preflight.claim_workload_role IS NULL
              OR preflight.claim_contract_version IS NULL
              OR preflight.claim_workload_role IS DISTINCT FROM 'preflight'
              OR preflight.claim_contract_version IS DISTINCT FROM 2
              OR preflight.dispatch_workload_role IS NULL
              OR preflight.dispatch_contract_version IS NULL
              OR preflight.dispatch_workload_role IS DISTINCT FROM 'preflight'
              OR preflight.dispatch_contract_version IS DISTINCT FROM 2
          )
    ) AS live_claim;

    -- An exact paid job claim is safe for normal V2 work. Missing, half, or
    -- mismatched claim/dispatch markers are legacy ownership and block.
    SELECT pg_catalog.count(*)
    INTO v_legacy_active_v2_job_claims
    FROM public.analysis_pipeline_jobs AS job
    WHERE job.status = 'processing'
      AND job.lease_token IS NOT NULL
      AND job.lease_expires_at > v_now
      AND (
          job.claim_workload_role IS NULL
          OR job.claim_contract_version IS NULL
          OR job.claim_workload_role IS DISTINCT FROM 'paid'
          OR job.claim_contract_version IS DISTINCT FROM 2
          OR job.dispatch_workload_role IS NULL
          OR job.dispatch_contract_version IS NULL
          OR job.dispatch_workload_role IS DISTINCT FROM 'paid'
          OR job.dispatch_contract_version IS DISTINCT FROM 2
      );

    SELECT pg_catalog.count(*)
    INTO v_legacy_active_old_target_invocations
    FROM public.analysis_requests AS request
    WHERE request.pipeline_version IS DISTINCT FROM 'v2'
      AND request.status IN ('pending', 'processing');

    -- Only unsafe active dispatches block. A completed ready ordinary
    -- preflight is intentionally excluded; exact role-aware pending and
    -- processing rows remain service-owned and recoverable.
    SELECT pg_catalog.count(*)
    INTO v_legacy_active_queued_preflight_tasks
    FROM public.analysis_preflights AS preflight
    WHERE preflight.status IN ('pending', 'processing')
      AND preflight.expires_at > v_now
      AND preflight.dispatch_state IN ('reserved', 'enqueued')
      AND (
          preflight.analysis_entry_channel = 'betatest'
          OR preflight.dispatch_workload_role IS NULL
          OR preflight.dispatch_contract_version IS NULL
          OR preflight.dispatch_workload_role IS DISTINCT FROM 'preflight'
          OR preflight.dispatch_contract_version IS DISTINCT FROM 2
          OR (
              preflight.dispatch_state = 'reserved'
              AND (
                  preflight.dispatch_token IS NULL
                  OR preflight.dispatch_reserved_at IS NULL
              )
          )
          OR (
              preflight.dispatch_state = 'enqueued'
              AND (
                  preflight.last_dispatch_token IS NULL
                  OR preflight.dispatch_reserved_at IS NULL
                  OR preflight.dispatched_at IS NULL
              )
          )
      );

    SELECT pg_catalog.count(*)
    INTO v_legacy_active_queued_v2_tasks
    FROM public.analysis_pipeline_jobs AS job
    WHERE job.status IN ('pending', 'processing')
      AND job.dispatch_state IN ('reserved', 'enqueued', 'delivered')
      AND (
          job.dispatch_workload_role IS NULL
          OR job.dispatch_contract_version IS NULL
          OR job.dispatch_workload_role IS DISTINCT FROM 'paid'
          OR job.dispatch_contract_version IS DISTINCT FROM 2
          OR job.dispatch_reserved_at IS NULL
          OR job.dispatched_at IS NULL
          OR job.dispatch_task_name IS NULL
      );

    -- Fresh admission safety is the inverse of the old broad counter: a live
    -- exact admission is safe, while a live admission claim without its exact
    -- active ledger is unsafe and must block promotion.
    SELECT pg_catalog.count(*)
    INTO v_legacy_active_fresh_admissions
    FROM public.analysis_preflights AS preflight
    WHERE preflight.status IN ('pending', 'processing')
      AND preflight.expires_at > v_now
      AND (
          (
              preflight.admission_status = 'processing'
              AND preflight.admission_claim_token IS NOT NULL
              AND preflight.admission_lease_expires_at > v_now
              AND NOT (
                  -- A trusted paid claim is sufficient for a fresh worker to
                  -- perform its admission transition. Otherwise an exact,
                  -- still-active admission lease is the durable proof. A live
                  -- claim with neither proof is the unsafe case.
                  (
                      preflight.admission_claim_workload_role IS NOT NULL
                      AND preflight.admission_claim_contract_version IS NOT NULL
                      AND preflight.admission_claim_workload_role IS NOT DISTINCT FROM 'paid'
                      AND preflight.admission_claim_contract_version IS NOT DISTINCT FROM 2
                  )
                  OR EXISTS (
                      SELECT 1
                      FROM public.analysis_provider_admission_leases AS admission
                      WHERE admission.workload_role = 'paid'
                        AND admission.logical_provider = 'apify'
                        AND admission.request_id = preflight.id
                        AND admission.job_key = 'paid:target-profile'
                        AND admission.operation_key =
                            'target-profile-fresh-admission:g' || preflight.admission_generation::TEXT
                        AND admission.job_claim_token = preflight.admission_claim_token
                        AND admission.claim_token = preflight.admission_claim_token
                        AND admission.state IN ('leased', 'recovery_required')
                        AND admission.expires_at > v_now
                  )
              )
          )
          OR (
              preflight.admission_dispatch_state IN ('reserved', 'enqueued')
              AND (
                  preflight.admission_dispatch_workload_role IS NULL
                  OR preflight.admission_dispatch_contract_version IS NULL
                  OR preflight.admission_dispatch_workload_role IS DISTINCT FROM 'paid'
                  OR preflight.admission_dispatch_contract_version IS DISTINCT FROM 2
                  OR preflight.admission_dispatch_token IS NULL
                  OR preflight.admission_dispatch_reserved_at IS NULL
              )
          )
      );

    -- Beta preparation is an explicitly retired producer in the active
    -- exact-three preflight service. Include queued/claimed/active rows, but
    -- not a completed prepared/expired historical row.
    SELECT pg_catalog.count(*)
    INTO v_legacy_active_beta_prepare
    FROM public.analysis_preflights AS preflight
    WHERE preflight.analysis_entry_channel = 'betatest'
      AND preflight.expires_at > v_now
      AND (
          preflight.status IN ('pending', 'processing')
          OR preflight.beta_prepare_state IN ('reserved', 'preparing')
          OR preflight.beta_prepare_dispatch_state IN ('reserved', 'enqueued')
          OR (
              preflight.beta_prepare_lease_token IS NOT NULL
              AND preflight.beta_prepare_lease_expires_at > v_now
          )
      );

    SELECT pg_catalog.count(*)
    INTO v_unreconciled_provider_runs
    FROM public.analysis_v2_provider_runs AS provider_run
    WHERE provider_run.status IN ('succeeded', 'failed', 'aborted', 'timed_out')
      AND provider_run.usage_reconciled_at IS NULL;

    SELECT pg_catalog.count(*)
    INTO v_unreconciled_preflight_runs
    FROM public.analysis_preflight_provider_runs AS provider_run
    WHERE provider_run.status IN ('succeeded', 'failed', 'aborted', 'timed_out')
      AND provider_run.usage_reconciled_at IS NULL;

    SELECT pg_catalog.count(*)
    INTO v_unreconciled_profile_repair_runs
    FROM public.analysis_v2_profile_repair_canary_runs AS canary_run
    WHERE canary_run.state IN ('succeeded', 'failed')
      AND canary_run.usage_reconciled_at IS NULL;

    SELECT pg_catalog.count(*)
    INTO v_unreconciled_v1_provider_runs
    FROM public.analysis_provider_runs AS provider_run;

    SELECT pg_catalog.count(*)
    INTO v_unreconciled_profile_provider_canary_runs
    FROM public.analysis_v2_profile_provider_canary_runs AS canary_run
    WHERE canary_run.state IN ('succeeded', 'failed', 'verified_no_run')
      AND canary_run.usage_reconciled_at IS NULL;

    RETURN pg_catalog.jsonb_build_object(
        'ready',
            v_legacy_active_provider_runs = 0
            AND v_legacy_active_preflight_runs = 0
            AND v_legacy_active_profile_repair_runs = 0
            AND v_legacy_active_v1_provider_runs = 0
            AND v_legacy_active_processing_claims = 0
            AND v_legacy_active_v2_job_claims = 0
            AND v_legacy_active_profile_provider_canary_runs = 0
            AND v_legacy_active_old_target_invocations = 0
            AND v_legacy_active_queued_preflight_tasks = 0
            AND v_legacy_active_queued_v2_tasks = 0
            AND v_legacy_active_fresh_admissions = 0
            AND v_legacy_active_beta_prepare = 0
            AND v_unreconciled_provider_runs = 0
            AND v_unreconciled_preflight_runs = 0
            AND v_unreconciled_profile_repair_runs = 0
            AND v_unreconciled_v1_provider_runs = 0
            AND v_unreconciled_profile_provider_canary_runs = 0,
        'legacyActiveProviderRuns', v_legacy_active_provider_runs,
        'legacyActivePreflightRuns', v_legacy_active_preflight_runs,
        'legacyActiveProfileRepairRuns', v_legacy_active_profile_repair_runs,
        'legacyActiveV1ProviderRuns', v_legacy_active_v1_provider_runs,
        'legacyActiveProcessingClaims', v_legacy_active_processing_claims,
        'legacyActiveV2JobClaims', v_legacy_active_v2_job_claims,
        'legacyActiveProfileProviderCanaryRuns', v_legacy_active_profile_provider_canary_runs,
        'legacyActiveOldTargetInvocations', v_legacy_active_old_target_invocations,
        'legacyActiveQueuedPreflightTasks', v_legacy_active_queued_preflight_tasks,
        'legacyActiveQueuedV2Tasks', v_legacy_active_queued_v2_tasks,
        'legacyActiveFreshAdmissions', v_legacy_active_fresh_admissions,
        'legacyActiveBetaPrepare', v_legacy_active_beta_prepare,
        'unreconciledProviderRuns', v_unreconciled_provider_runs,
        'unreconciledPreflightRuns', v_unreconciled_preflight_runs,
        'unreconciledProfileRepairRuns', v_unreconciled_profile_repair_runs,
        'unreconciledV1ProviderRuns', v_unreconciled_v1_provider_runs,
        'unreconciledProfileProviderCanaryRuns', v_unreconciled_profile_provider_canary_runs,
        'legacyActiveTotal',
            v_legacy_active_provider_runs
            + v_legacy_active_preflight_runs
            + v_legacy_active_profile_repair_runs
            + v_legacy_active_v1_provider_runs
            + v_legacy_active_processing_claims
            + v_legacy_active_v2_job_claims
            + v_legacy_active_profile_provider_canary_runs
            + v_legacy_active_old_target_invocations
            + v_legacy_active_queued_preflight_tasks
            + v_legacy_active_queued_v2_tasks
            + v_legacy_active_fresh_admissions
            + v_legacy_active_beta_prepare,
        'unreconciledTotal',
            v_unreconciled_provider_runs
            + v_unreconciled_preflight_runs
            + v_unreconciled_profile_repair_runs
            + v_unreconciled_v1_provider_runs
            + v_unreconciled_profile_provider_canary_runs
    );
END;
$$;

-- Capacity waits are durable, attempt-neutral B-lite deferrals.  The cache claim is rearmed
-- before the shared Gemini admission is released by the worker, so a redelivery can claim the
-- same source without consuming the two-attempt inference budget.  A false result is a stale
-- worker/token and must never mutate another owner's cache row.
CREATE OR REPLACE FUNCTION public.defer_precheckout_blite_v2_capacity(
    p_preflight_id UUID,
    p_lease_token UUID
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_now TIMESTAMPTZ;
    v_preflight public.analysis_preflights%ROWTYPE;
    v_cache public.precheckout_blite_cache%ROWTYPE;
BEGIN
    IF p_preflight_id IS NULL OR p_lease_token IS NULL THEN
        RETURN FALSE;
    END IF;
    SELECT preflight.* INTO v_preflight
    FROM public.analysis_preflights AS preflight
    WHERE preflight.id = p_preflight_id
    FOR UPDATE;
    IF NOT FOUND OR v_preflight.status IS DISTINCT FROM 'ready'
       OR v_preflight.precheckout_blite_cohort IS DISTINCT FROM TRUE THEN
        RETURN FALSE;
    END IF;
    SELECT cache.* INTO v_cache
    FROM public.precheckout_blite_cache AS cache
    WHERE cache.preflight_id = p_preflight_id
    FOR UPDATE;
    v_now := pg_catalog.clock_timestamp();
    IF NOT FOUND
       OR v_cache.state IS DISTINCT FROM 'pending'
       OR v_cache.lease_token IS DISTINCT FROM p_lease_token THEN
        RETURN FALSE;
    END IF;
    UPDATE public.precheckout_blite_cache AS cache
    SET lease_token = extensions.gen_random_uuid(),
        lease_expires_at = v_now,
        attempt_count = CASE
            WHEN cache.attempt_count > 0 THEN cache.attempt_count - 1
            ELSE 0
        END,
        updated_at = v_now
    WHERE cache.preflight_id = p_preflight_id
      AND cache.state = 'pending'
      AND cache.lease_token = p_lease_token;
    RETURN FOUND;
END;
$$;

-- Re-declare the existing V2 AI capacity deferral contract in this additive migration.  The
-- predecessor migration is immutable; this keeps provider-admission capacity waits attempt
-- neutral without rewriting an already-applied migration.
CREATE OR REPLACE FUNCTION public.defer_analysis_v2_job_for_ai_capacity(
    p_request_id UUID,
    p_job_key TEXT,
    p_claim_token UUID,
    p_error_code TEXT
)
RETURNS TABLE(
    released BOOLEAN,
    job_status TEXT,
    attempt_count INTEGER,
    request_status TEXT,
    ai_capacity_deferral_count INTEGER
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_now TIMESTAMPTZ := pg_catalog.clock_timestamp();
    v_request public.analysis_requests%ROWTYPE;
    v_job public.analysis_pipeline_jobs%ROWTYPE;
BEGIN
    IF p_request_id IS NULL OR p_claim_token IS NULL
       OR p_error_code NOT IN (
            'ANALYSIS_V2_AI_CAPACITY_PENDING',
            'ANALYSIS_V2_PROVIDER_ADMISSION_CAPACITY_PENDING',
            'ANALYSIS_V2_AI_DEADLINE_TOO_SHORT',
            'ANALYSIS_V2_AI_QUARANTINE_ACTIVE',
            'ANALYSIS_V2_AI_RESULT_RECOVERY_PENDING'
       )
       OR p_job_key IS NULL
       OR pg_catalog.char_length(p_job_key) NOT BETWEEN 1 AND 160
       OR p_job_key !~ '^[a-z0-9][a-z0-9:._-]{0,159}$' THEN
        RAISE EXCEPTION USING
            MESSAGE = 'ANALYSIS_V2_AI_CAPACITY_DEFER_INVALID', ERRCODE = 'P0001';
    END IF;

    PERFORM 1
    FROM public.analysis_preflights AS preflight
    WHERE preflight.consumed_request_id = p_request_id
    FOR UPDATE;
    SELECT analysis_request.* INTO v_request
    FROM public.analysis_requests AS analysis_request
    WHERE analysis_request.id = p_request_id
      AND analysis_request.pipeline_version = 'v2'
    FOR UPDATE;
    IF NOT FOUND OR v_request.status NOT IN ('pending', 'processing') THEN
        RAISE EXCEPTION USING
            MESSAGE = 'ANALYSIS_V2_AI_CAPACITY_DEFER_NOT_READY', ERRCODE = 'P0001';
    END IF;

    SELECT job.* INTO v_job
    FROM public.analysis_pipeline_jobs AS job
    WHERE job.request_id = p_request_id
      AND job.job_key = p_job_key
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING
            MESSAGE = 'ANALYSIS_V2_JOB_NOT_FOUND', ERRCODE = 'P0001';
    END IF;
    IF v_job.status <> 'processing'
       OR v_job.lease_token IS DISTINCT FROM p_claim_token
       OR v_job.lease_expires_at IS NULL
       OR v_job.lease_expires_at <= v_now
       OR v_job.attempt_count < 1 THEN
        RAISE EXCEPTION USING
            MESSAGE = 'ANALYSIS_V2_JOB_LEASE_FENCE_MISMATCH', ERRCODE = 'P0001';
    END IF;

    UPDATE public.analysis_pipeline_jobs AS job
    SET status = 'pending',
        lease_token = NULL,
        lease_expires_at = NULL,
        attempt_count = CASE
            WHEN job.attempt_count > 0 THEN job.attempt_count - 1
            ELSE 0
        END,
        first_started_at = CASE
            WHEN job.attempt_count = 1 THEN NULL
            ELSE job.first_started_at
        END,
        ai_capacity_deferral_count = job.ai_capacity_deferral_count + 1,
        last_error_code = p_error_code,
        last_error_at = v_now,
        updated_at = v_now
    WHERE job.request_id = p_request_id
      AND job.job_key = p_job_key
      AND job.status = 'processing'
      AND job.lease_token = p_claim_token
    RETURNING job.* INTO v_job;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING
            MESSAGE = 'ANALYSIS_V2_JOB_LEASE_FENCE_MISMATCH', ERRCODE = 'P0001';
    END IF;

    RETURN QUERY SELECT
        TRUE,
        v_job.status::TEXT,
        v_job.attempt_count,
        v_request.status::TEXT,
        v_job.ai_capacity_deferral_count;
END;
$$;

