-- B-lite has its own preflight dispatch and cache-claim markers so a generic ordinary task can
-- never be mistaken for a B-lite invocation during readiness or recovery.
CREATE OR REPLACE FUNCTION public.reserve_precheckout_blite_dispatch_v2(
    p_preflight_id UUID,
    p_workload_role TEXT,
    p_contract_version SMALLINT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_dispatch public.precheckout_blite_dispatches%ROWTYPE;
    v_result JSONB;
BEGIN
    IF p_workload_role IS DISTINCT FROM 'preflight' OR p_contract_version IS DISTINCT FROM 2 THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_WORKLOAD_ROLE_MISMATCH', ERRCODE = 'P0001';
    END IF;
    -- A roleless predecessor belongs to the mixed-version drain cohort.  It
    -- must never be upgraded merely because a new worker retries the same
    -- preflight id: doing so would manufacture a role-aware successor that
    -- the old task can neither claim nor safely fence.  An idle roleless row
    -- is still eligible for a genuinely new v2 reservation; every active or
    -- reserved roleless row remains drain-only.
    SELECT dispatch.* INTO v_dispatch
    FROM public.precheckout_blite_dispatches AS dispatch
    WHERE dispatch.preflight_id = p_preflight_id
    FOR UPDATE;
    IF FOUND AND v_dispatch.state IN ('reserved', 'enqueuing', 'enqueued')
       AND v_dispatch.dispatch_workload_role IS NULL
       AND v_dispatch.dispatch_contract_version IS NULL THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_V2_LEGACY_DISPATCH_ROLELESS', ERRCODE = 'P0001';
    END IF;
    IF FOUND AND (
        (v_dispatch.dispatch_workload_role IS NULL
            AND v_dispatch.dispatch_contract_version IS NOT NULL)
        OR (v_dispatch.dispatch_workload_role IS NOT NULL
            AND v_dispatch.dispatch_contract_version IS NULL)
        OR (v_dispatch.dispatch_workload_role IS NOT NULL
            AND v_dispatch.dispatch_workload_role IS DISTINCT FROM 'preflight')
        OR (v_dispatch.dispatch_contract_version IS NOT NULL
            AND v_dispatch.dispatch_contract_version IS DISTINCT FROM 2)
    ) THEN
        RAISE EXCEPTION USING MESSAGE = 'ANALYSIS_WORKLOAD_ROLE_MISMATCH', ERRCODE = 'P0001';
    END IF;
    v_result := public.reserve_precheckout_blite_dispatch_v1(p_preflight_id);
    IF COALESCE((v_result->>'should_enqueue')::BOOLEAN, FALSE) THEN
        UPDATE public.precheckout_blite_dispatches AS dispatch
        SET dispatch_workload_role = 'preflight', dispatch_contract_version = 2
        WHERE dispatch.preflight_id = p_preflight_id
          AND dispatch.state = 'enqueuing'
          AND dispatch.dispatch_token = (v_result->>'dispatch_token')::UUID;
        IF NOT FOUND THEN
            RAISE EXCEPTION USING MESSAGE = 'PRECHECKOUT_BLITE_DISPATCH_FENCE_LOST', ERRCODE = 'P0001';
        END IF;
    END IF;
    RETURN v_result;
END;
$$;

CREATE OR REPLACE FUNCTION public.rearm_precheckout_blite_dispatch_v3(
    p_preflight_id UUID,
    p_expected_generation INTEGER,
    p_expected_dispatch_token UUID,
    p_workload_role TEXT,
    p_contract_version SMALLINT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_now TIMESTAMPTZ := pg_catalog.clock_timestamp();
    v_new_token UUID := extensions.gen_random_uuid();
    v_dispatch public.precheckout_blite_dispatches%ROWTYPE;
    v_generation INTEGER;
BEGIN
    IF p_workload_role IS DISTINCT FROM 'preflight'
       OR p_contract_version IS DISTINCT FROM 2
       OR p_expected_generation IS NULL
       OR p_expected_generation NOT BETWEEN 1 AND 100
       OR p_expected_dispatch_token IS NULL THEN
        RETURN pg_catalog.jsonb_build_object(
            'should_enqueue', FALSE,
            'dispatch_generation', COALESCE(p_expected_generation, 1),
            'dispatch_token', NULL
        );
    END IF;
    SELECT dispatch.* INTO v_dispatch
    FROM public.precheckout_blite_dispatches AS dispatch
    WHERE dispatch.preflight_id = p_preflight_id
    FOR UPDATE;
    IF NOT FOUND
       OR v_dispatch.state IS DISTINCT FROM 'enqueued'
       OR v_dispatch.dispatch_generation IS DISTINCT FROM p_expected_generation
       OR v_dispatch.last_dispatch_token IS DISTINCT FROM p_expected_dispatch_token
       OR v_dispatch.dispatch_workload_role IS DISTINCT FROM 'preflight'
       OR v_dispatch.dispatch_contract_version IS DISTINCT FROM 2 THEN
        RETURN pg_catalog.jsonb_build_object(
            'should_enqueue', FALSE,
            'dispatch_generation', COALESCE(v_dispatch.dispatch_generation, p_expected_generation),
            'dispatch_token', NULL
        );
    END IF;
    v_generation := p_expected_generation + 1;
    IF v_generation > 100 THEN
        RAISE EXCEPTION USING MESSAGE = 'PRECHECKOUT_BLITE_DISPATCH_GENERATION_EXHAUSTED', ERRCODE = 'P0001';
    END IF;
    UPDATE public.precheckout_blite_dispatches AS dispatch
    SET state = 'enqueuing',
        dispatch_generation = v_generation,
        dispatch_token = v_new_token,
        last_dispatch_token = NULL,
        attempt_count = dispatch.attempt_count + 1,
        lease_expires_at = v_now + INTERVAL '2 minutes',
        failure_reason = NULL,
        updated_at = v_now
    WHERE dispatch.preflight_id = p_preflight_id
      AND dispatch.state = 'enqueued'
      AND dispatch.dispatch_generation = p_expected_generation
      AND dispatch.last_dispatch_token = p_expected_dispatch_token
      AND dispatch.dispatch_workload_role = 'preflight'
      AND dispatch.dispatch_contract_version = 2;
    IF NOT FOUND THEN
        RETURN pg_catalog.jsonb_build_object(
            'should_enqueue', FALSE,
            'dispatch_generation', p_expected_generation,
            'dispatch_token', NULL
        );
    END IF;
    RETURN pg_catalog.jsonb_build_object(
        'should_enqueue', TRUE,
        'dispatch_generation', v_generation,
        'dispatch_token', v_new_token
    );
END;
$$;

