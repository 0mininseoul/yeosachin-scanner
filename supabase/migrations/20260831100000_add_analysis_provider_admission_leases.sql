CREATE OR REPLACE FUNCTION public.defer_analysis_preflight_for_provider_capacity(
    p_preflight_id UUID,
    p_claim_token UUID
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_now TIMESTAMPTZ := pg_catalog.clock_timestamp();
BEGIN
    IF p_preflight_id IS NULL OR p_claim_token IS NULL THEN
        RETURN FALSE;
    END IF;
    UPDATE public.analysis_preflights AS preflight
    SET status = 'pending',
        lease_token = NULL,
        lease_expires_at = NULL,
        worker_attempt_count = CASE
            WHEN preflight.worker_attempt_count > 0 THEN preflight.worker_attempt_count - 1
            ELSE 0
        END,
        updated_at = v_now
    WHERE preflight.id = p_preflight_id
      AND preflight.status = 'processing'
      AND preflight.lease_token = p_claim_token
      AND preflight.lease_expires_at > v_now
      AND preflight.worker_attempt_count >= 1
      AND preflight.expires_at > v_now
      AND preflight.dispatch_state = 'enqueued';
    RETURN FOUND;
END;
$$;

CREATE OR REPLACE FUNCTION public.rearm_analysis_preflight_dispatch_for_provider_capacity_v2(
    p_preflight_id UUID,
    p_expected_generation INTEGER,
    p_expected_reservation_token UUID
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_now TIMESTAMPTZ := pg_catalog.clock_timestamp();
    v_new_token UUID := extensions.gen_random_uuid();
    v_preflight public.analysis_preflights%ROWTYPE;
    v_generation INTEGER;
BEGIN
    IF p_preflight_id IS NULL OR p_expected_generation IS NULL
       OR p_expected_generation < 1 OR p_expected_generation > 100
       OR p_expected_reservation_token IS NULL THEN
        RETURN pg_catalog.jsonb_build_object(
            'should_enqueue', FALSE,
            'dispatch_generation', COALESCE(p_expected_generation, 1),
            'reservation_token', NULL
        );
    END IF;
    SELECT preflight.* INTO v_preflight
    FROM public.analysis_preflights AS preflight
    WHERE preflight.id = p_preflight_id
    FOR UPDATE;
    v_now := pg_catalog.clock_timestamp();
    IF NOT FOUND
       OR v_preflight.status IS DISTINCT FROM 'pending'
       OR v_preflight.dispatch_workload_role IS DISTINCT FROM 'preflight'
       OR v_preflight.dispatch_contract_version IS DISTINCT FROM 2
       OR v_preflight.expires_at <= v_now
       OR v_preflight.dispatch_state IS DISTINCT FROM 'enqueued'
       OR v_preflight.dispatch_generation IS DISTINCT FROM p_expected_generation
       OR v_preflight.last_dispatch_token IS DISTINCT FROM p_expected_reservation_token THEN
        RETURN pg_catalog.jsonb_build_object(
            'should_enqueue', FALSE,
            'dispatch_generation', COALESCE(v_preflight.dispatch_generation,
                p_expected_generation),
            'reservation_token', NULL
        );
    END IF;
    v_generation := v_preflight.dispatch_generation + 1;
    IF v_generation > 100 THEN
        RAISE EXCEPTION USING MESSAGE = 'PREFLIGHT_DISPATCH_GENERATION_EXHAUSTED', ERRCODE = 'P0001';
    END IF;
    UPDATE public.analysis_preflights AS preflight
    SET dispatch_state = 'reserved',
        dispatch_generation = v_generation,
        dispatch_token = v_new_token,
        last_dispatch_token = NULL,
        dispatch_reserved_at = v_now,
        dispatched_at = NULL,
        updated_at = v_now
    WHERE preflight.id = p_preflight_id
      AND preflight.status = 'pending'
      AND preflight.dispatch_state = 'enqueued'
      AND preflight.dispatch_generation = p_expected_generation
      AND preflight.last_dispatch_token = p_expected_reservation_token;
    IF NOT FOUND THEN
        RETURN pg_catalog.jsonb_build_object(
            'should_enqueue', FALSE,
            'dispatch_generation', p_expected_generation,
            'reservation_token', NULL
        );
    END IF;
    RETURN pg_catalog.jsonb_build_object(
        'should_enqueue', TRUE,
        'dispatch_generation', v_generation,
        'reservation_token', v_new_token
    );
END;
$$;

