-- Database-global provider admission for the split preflight/paid workers.
-- This is additive and intentionally does not remove or rewrite legacy ledgers.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '2min';

CREATE TABLE IF NOT EXISTS public.analysis_provider_admission_budgets (
    budget_key TEXT PRIMARY KEY,
    workload_role TEXT NOT NULL CHECK (workload_role IN ('preflight', 'paid')),
    logical_provider TEXT NOT NULL CHECK (logical_provider IN ('apify', 'gemini')),
    credential_slot TEXT,
    max_active INTEGER NOT NULL CHECK (max_active BETWEEN 1 AND 100000),
    rate_limit_per_minute INTEGER NOT NULL CHECK (rate_limit_per_minute BETWEEN 1 AND 1000000),
    window_started_at TIMESTAMPTZ NOT NULL DEFAULT pg_catalog.clock_timestamp(),
    window_count INTEGER NOT NULL DEFAULT 0 CHECK (window_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT pg_catalog.clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT pg_catalog.clock_timestamp(),
    CONSTRAINT analysis_provider_admission_budget_key_check CHECK (
        budget_key ~ '^(preflight|paid):(apify|gemini):[a-z0-9:_-]{1,96}$'
    ),
    CONSTRAINT analysis_provider_admission_budget_slot_check CHECK (
        credential_slot IS NULL OR credential_slot ~ '^[a-z][a-z0-9_-]{1,31}$'
    ),
    CONSTRAINT analysis_provider_admission_budget_clock_check CHECK (
        updated_at >= created_at
    )
);

CREATE TABLE IF NOT EXISTS public.analysis_provider_admission_leases (
    admission_id TEXT PRIMARY KEY,
    workload_role TEXT NOT NULL CHECK (workload_role IN ('preflight', 'paid')),
    logical_provider TEXT NOT NULL CHECK (logical_provider IN ('apify', 'gemini')),
    credential_slot TEXT NOT NULL CHECK (credential_slot ~ '^[a-z][a-z0-9_-]{1,31}$'),
    budget_key TEXT NOT NULL REFERENCES public.analysis_provider_admission_budgets(budget_key),
    request_id UUID NOT NULL,
    job_key TEXT NOT NULL CHECK (job_key ~ '^[a-z0-9][a-z0-9:._-]{0,159}$'),
    operation_key TEXT NOT NULL CHECK (operation_key ~ '^[a-z0-9][a-z0-9:._-]{0,255}$'),
    -- `claim_token` is the provider-ledger claim (the Gemini slot claim for
    -- Gemini admissions). Job ownership is a separate fence because a Gemini
    -- slot claim is intentionally generated by the Gemini lease RPC.
    claim_token UUID NOT NULL,
    job_claim_token UUID NOT NULL,
    -- Gemini also records the authoritative slot fence. Apify has no second
    -- provider ledger fence and therefore leaves this nullable.
    provider_fence BIGINT,
    lease_token UUID NOT NULL,
    fence BIGINT NOT NULL DEFAULT 1 CHECK (fence >= 1),
    state TEXT NOT NULL DEFAULT 'leased'
        CHECK (state IN ('leased', 'released', 'recovery_required')),
    acquired_at TIMESTAMPTZ NOT NULL DEFAULT pg_catalog.clock_timestamp(),
    expires_at TIMESTAMPTZ NOT NULL,
    released_at TIMESTAMPTZ,
    recovered_at TIMESTAMPTZ,
    release_reason TEXT,
    resolution_source TEXT,
    resolution_token_hash TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT pg_catalog.clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT pg_catalog.clock_timestamp(),
    CONSTRAINT analysis_provider_admission_lease_id_check CHECK (
        admission_id ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT analysis_provider_admission_lease_time_check CHECK (
        updated_at >= created_at
    ),
    CONSTRAINT analysis_provider_admission_provider_fence_check CHECK (
        provider_fence IS NULL OR provider_fence >= 1
    ),
    CONSTRAINT analysis_provider_admission_lease_terminal_check CHECK (
        (
            state = 'leased'
            AND released_at IS NULL
            AND release_reason IS NULL
            AND resolution_source IS NULL
            AND resolution_token_hash IS NULL
        )
        OR (
            state = 'released'
            AND released_at IS NOT NULL
            AND release_reason IN ('terminal', 'prestart_rejected', 'ledger_resolved')
            AND (
                release_reason <> 'ledger_resolved'
                OR (
                    resolution_source IN (
                        'provider_ledger_terminal',
                        'provider_ledger_absent',
                        'gemini_lease_fenced'
                    )
                    AND resolution_token_hash ~ '^[a-f0-9]{64}$'
                )
            )
        )
        OR (
            state = 'recovery_required'
            AND recovered_at IS NOT NULL
            AND released_at IS NULL
            AND release_reason IS NULL
            AND resolution_source IS NULL
            AND resolution_token_hash IS NULL
        )
    ),
    CONSTRAINT analysis_provider_admission_lease_identity_unique UNIQUE (
        workload_role, logical_provider, request_id, job_key, operation_key
    )
);

